@_guard
def cmd_freshen(args) -> int:
    facts = [f for f in _select(args) if f.get("status") not in ("rejected", "superseded")]
    pages = sorted({(e["source_id"], e["url"]) for f in facts for e in f["evidence"]})
    if args.limit:
        pages = pages[:args.limit]
    kept = {sid for sid, _url in pages}
    corpus = _corpus()
    report = {"pages": len(pages), "not_modified": 0, "changed": [], "facts_ok": 0, "facts_broken": [], "errors": []}
    asked = set()
    if not args.offline:
        for sid, url in pages:
            try:
                if corpus is None:
                    raise RuntimeError("the corpus module is not available")
                meta = corpus.fetch(url, revalidate=True, source_id=sid)
                asked.add(sid)
                if meta.get("state") == "not-modified":
                    report["not_modified"] += 1
                elif meta.get("state") == "changed":
                    report["changed"].append(sid)
            except Exception as exc:
                report["errors"].append({"url": url, "error": str(exc)[:300]})
    ctx = _Ctx()
    changes, broken, touched = {}, [], set()
    for fact in facts:
        if not all(e["source_id"] in kept for e in fact["evidence"]):
            continue
        updates, missing = [], False
        for ev in fact["evidence"]:
            snap = ctx.snap(ev["source_id"])
            hit = common.find_quote(ev["quote"], snap["norm"], already_normalized=True) if snap else None
            if snap is None or (snap["meta"] or {}).get("url") != ev["url"] or hit is None:
                missing = True
                break
            updates.append((snap["sha"], list(hit)))
        if missing:
            if fact.get("status") != "candidate" or fact.get("stale") != "quote-missing":
                def demote(row):
                    row.update(status="candidate", stale="quote-missing")
                changes[fact["id"]] = (fact["service"], demote)
            broken.append(fact)
            report["facts_broken"].append(fact["id"])
            continue
        report["facts_ok"] += 1
        fresh = all(e["source_id"] in asked for e in fact["evidence"])
        if fresh or any(e.get("sha256") != u[0] for e, u in zip(fact["evidence"], updates)):
            def refresh(row, updates=updates, fresh=fresh):
                for ev, (sha, match) in zip(row["evidence"], updates):
                    ev.update(sha256=sha, match=match)
                if fresh:
                    row["retrieved"] = common.today()
            changes[fact["id"]] = (fact["service"], refresh)
            touched.add(fact["service"])
    if changes:
        _update_facts(changes)
    for fact in broken:
        touched.add(fact["service"])
        _effects(fact, f"fact {fact['id']} quote-missing")
    sheets = _render(sorted(s for s in touched if (common.FACTSHEETS / f"{s}.md").exists()))
    path = common.REPORTS / f"freshen-{common.today()}.json"
    common.write_json(path, report)
    _out(args, report, f"freshen: {report['pages']} pages, {report['facts_ok']} facts ok, {len(report['facts_broken'])} broken, "
                       f"{len(report['errors'])} fetch errors; {_rel(path)}",
         [f"broken: {i}" for i in report["facts_broken"]] + [f"error: {e['url']}: {e['error']}" for e in report["errors"]]
         + [f"fact sheet rewritten: {p}" for p in sheets["written"]]
         + (["run `saa.py sync CH --only sources` for the chapters that cite these pages"] if touched else []))
    if report["facts_broken"]:
        return common.EXIT_FAIL
    return common.EXIT_TRANSIENT if report["errors"] else common.EXIT_OK


