def _holds(text: str, display: str) -> bool:
    """lint.holds_display, the one number-boundary rule of the book (W0 follow-up 3): a substring test where a
    display that starts or ends with a digit must not sit inside a longer number (`5 Gbps` in `45 Gbps`,
    `500 widgets` in `2 500 widgets`, `1,000` in `11,000`). Both arguments are normalised. Without the lint
    module (never the case in the book) it is a plain substring test."""
    try:
        from . import lint
        return bool(lint.holds_display(text, display))
    except Exception:
        return bool(display) and display in text


