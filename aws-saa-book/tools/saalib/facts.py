def _plain(text: str) -> str:
    """Case-preserving clean form of a claim, display or quote: entities, NFKC, quotes and dashes unified,
    tags and link targets dropped, Markdown escapes and emphasis removed."""
    t = html.unescape(text or "")
    t = unicodedata.normalize("NFKC", t).translate(_QT)
    t = _RE_TAG.sub(" ", t)
    t = _RE_IMG.sub(r"\1", t)
    for _ in range(3):
        t = _RE_LINK.sub(r"\1", t)
    t = _RE_ESCAPE.sub(r"\1", t)
    return t.replace("`", "").replace("*", "")


def _mask_dates(text: str):
    """Return (text with every date replaced by ' ; ', [ISO dates])."""
    dates = []

    def take(kind):
        def sub(m):
            g = m.groups()
            if kind == "iso":
                dates.append(f"{g[0]}-{g[1]}" + (f"-{g[2]}" if g[2] else ""))
            elif kind == "mdy":
                dates.append(f"{g[2]}-{_MONTHS[g[0].lower()]:02d}-{int(g[1]):02d}")
            elif kind == "dmy":
                dates.append(f"{g[2]}-{_MONTHS[g[1].lower()]:02d}-{int(g[0]):02d}")
            else:
                dates.append(f"{g[1]}-{_MONTHS[g[0].lower()]:02d}")
            return " ; "
        return sub

    for kind, rx in _RE_DATES:
        text = rx.sub(take(kind), text)
    return text, dates


def _date_eq(a: str, b: str) -> bool:
    return bool(a and b) and (a == b or (len(a) == 7 and b.startswith(a)) or (len(b) == 7 and a.startswith(b)))


def _names() -> tuple:
    """Lowercase terms and official service names: digits inside or directly after one are not numbers (R2)."""
    names = set()
    try:
        terms = common.read_json(common.DATA / "terms.json", {}) or {}
        services = common.read_json(common.REGISTRY / "services.json", {}) or {}
    except ValueError:
        return ()
    for term in terms.get("terms", []) if isinstance(terms, dict) else []:
        for key in ("term", "short"):
            if isinstance(term.get(key), str):
                names.add(term[key].lower())
    for entry in (services.get("in_scope") or []) + (services.get("out_of_scope") or []):
        for key in ("official_name", "short_name"):
            if isinstance(entry.get(key), str):
                names.add(entry[key].lower())
                names.add(re.sub(r"\s*\([^)]*\)\s*$", "", entry[key]).lower())
    return tuple(sorted((n for n in names if len(n) >= 2), key=len, reverse=True))


class _Ctx:
    """Everything the mechanical checks read, loaded once per command."""

    def __init__(self, quick=False):
        self.quick = quick
        self.book = common.load_book()
        self.keys = {}
        for ch in self.book.get("chapters", []):
            for s in ch.get("services") or []:
                self.keys.setdefault(s, ch["id"])
        for ns, ch in ((self.book.get("book") or {}).get("fact_namespaces") or {}).items():
            self.keys[ns] = ch
        lint = _spec().get("lint") or {}
        nwu = lint.get("number_with_unit") or {}
        self.units = list(nwu.get("units") or DEFAULT_UNITS)
        self.nouns = list(nwu.get("count_nouns") or [])
        self.absolute = list(lint.get("absolute_words") or DEFAULT_ABSOLUTE)
        alt = "|".join(re.escape(u) for u in sorted(self.units, key=len, reverse=True))
        self.unit_re = re.compile(r"[ \-]?(" + alt + r")(?![A-Za-z])")
        nalt = "|".join(re.escape(n) for n in sorted(self.nouns, key=len, reverse=True)) or r"(?!x)x"
        self.noun_re = re.compile(r"[ \-]?(" + nalt + r")(?![A-Za-z])", re.I)
        self.names = _names()
        self.id_count = collections.Counter()
        self.by_service = {}
        for service in _services():
            rows = _rows(service)
            self.by_service[service] = rows
            self.id_count.update(r.get("id") for r in rows)
        self._snaps = {}

    def unit_key(self, unit):
        unit = UNIT_ALIASES.get(unit, unit)
        if unit and unit.endswith("s") and unit[:-1] in self.units:
            unit = unit[:-1]
        return UNIT_ALIASES.get(unit, unit)

    def snap(self, source_id):
        if source_id not in self._snaps:
            base = _snap_base(source_id)
            snap = None
            if base and Path(base + ".txt").exists():
                text = Path(base + ".txt").read_text(encoding="utf-8", errors="replace")
                try:
                    meta = common.read_json(Path(base + ".meta.json"))
                except ValueError:
                    meta = None
                snap = {"text": text, "norm": common.normalize_text(text), "sha": common.sha256_file(Path(base + ".txt")),
                        "meta": meta, "lines": text.splitlines(), "norm_lines": None}
            self._snaps[source_id] = snap
        return self._snaps[source_id]

    def norm_lines(self, snap):
        if snap["norm_lines"] is None:
            snap["norm_lines"] = [common.normalize_text(line) for line in snap["lines"]]
        return snap["norm_lines"]

    def layout(self, snap):
        """The normalised lines joined by one space, with the span and the kind of each line.

        Returns (joined text, [(start, end, kind)]) with kind `heading`, `table` or `text`.
        """
        if snap.get("layout") is None:
            parts, spans, pos = [], [], 0
            for raw, norm in zip(snap["lines"], self.norm_lines(snap)):
                if not norm:
                    continue
                kind = "heading" if _RE_HEADING.match(raw) else "table" if raw.lstrip().startswith("|") else "text"
                spans.append((pos, pos + len(norm), kind))
                parts.append(norm)
                pos += len(norm) + 1
            snap["layout"] = (" ".join(parts), spans)
        return snap["layout"]


def _follows_name(text: str, start: int, ctx) -> bool:
    if start < 2 or text[start - 1] != " ":
        return False
    before = text[:start - 1].lower()
    for name in ctx.names:
        if before.endswith(name) and (len(before) == len(name) or not before[-len(name) - 1].isalnum()):
            return True
    return False


def _scan_numbers(text: str, ctx, quote_side=False) -> list:
    """Numbers of a cleaned text whose dates are masked. Each: num (digits, no separators), unit, noun, money, word.

    Not a number: digits glued to letters (S3, EC2, us-east-1, gp3, 4xx), digits inside a term or an official
    service name (Route 53), and, on the claim side, a bare number directly after such a name (TLS 1.2).
    A number word (zero to twelve) counts on the quote side always, on the claim side only before a unit or a
    count noun.
    """
    low = text.lower()
    chars = list(text)
    for name in ctx.names:
        if not any(c.isdigit() for c in name):
            continue
        at = low.find(name)
        while at >= 0:
            for i in range(at, at + len(name)):
                if chars[i].isdigit():
                    chars[i] = "#"
            at = low.find(name, at + 1)
    text = "".join(chars)
    out = []
    for m in _RE_NUM.finditer(text):
        end = m.end()
        um = ctx.unit_re.match(text, end)
        nm = None if um else ctx.noun_re.match(text, end)
        if not um and not nm and re.match(r"(?:st|nd|rd|th|xx|xlarge)(?![A-Za-z])", text[end:]):
            continue                        # 3rd, 4xx, 2xlarge
        if text[end:end + 1] == "#":
            continue
        if not quote_side and not um and not nm and not m.group(1) and _follows_name(text, m.start(), ctx):
            continue
        out.append({"num": m.group(2).replace(",", ""), "unit": um.group(1) if um else None, "noun": bool(nm),
                    "money": bool(m.group(1)), "word": False, "start": m.start(), "end": (um or nm or m).end(),
                    "num_end": end})
    for n in out:               # gate-break H2: `50 thousand`, `50K`, and a unit after one or two words (`7 full hours`)
        mm = None if n["unit"] else _RE_MAG.match(text, n["num_end"])
        n["mag"] = MAGNITUDES[(mm.group(1) or mm.group(2)).lower()] if mm else None
        if not n["unit"] and not n["noun"] and not mm:
            gap = _gap_unit(text, n["num_end"], ctx)
            if gap:
                n["unit"], n["end"] = gap.group(1), gap.end()
    for m in _RE_WORDPHRASE.finditer(text):
        words = re.split(r"[ -]+", m.group(0).lower())
        small = len(words) == 1 and words[0] in NUMBER_WORDS
        if any(n.get("mag") and n["num_end"] <= m.start() <= n["num_end"] + 1 for n in out):
            continue                        # the magnitude word of `50 thousand` is no number of its own
        um = ctx.unit_re.match(text, m.end())
        nm = None if um else ctx.noun_re.match(text, m.end())
        # one small word (zero to twelve) is a number on the claim side only before a unit or a count noun;
        # a larger or compound number word (`nineteen`, `nine hundred`) always is
        if quote_side or um or nm or not small:
            out.append({"num": NUMBER_WORDS[words[0]] if small else _word_value(words), "unit": um.group(1) if um else None,
                        "noun": bool(nm), "money": False, "word": small, "mag": None, "start": m.start(),
                        "end": (um or nm or m).end(), "num_end": m.end()})
    out.sort(key=lambda n: n["start"])
    if quote_side:      # "5 to 10 GB": the first number of a range takes the unit of the second
        for i in range(len(out) - 2, -1, -1):
            nxt = out[i + 1]
            if out[i]["unit"] is None and nxt["unit"] and _RE_RANGE.match(text[out[i]["num_end"]:nxt["start"]]):
                out[i]["unit"] = nxt["unit"]
    return out


def _gap_unit(text: str, end: int, ctx):
    """The unit that follows a number after one or two plain words (`7 full hours`), or None."""
    pos = end
    for _ in range(2):
        word = _RE_GAPWORD.match(text, pos)
        if not word or word.group(1).lower() in GAP_STOP or ctx.unit_re.fullmatch(" " + word.group(1)):
            return None
        pos = word.end()
        unit = ctx.unit_re.match(text, pos)
        if unit and unit.group(0)[0] in " -":
            return unit
    return None


def _word_value(words: list) -> str:
    """`nine hundred` -> '900', `twenty five` -> '25', `two thousand five hundred` -> '2500'."""
    total = current = 0
    for word in words:
        value = WORD_VALUES[word]
        if value == 100:
            current = max(current, 1) * 100
        elif value >= 1000:
            total += max(current, 1) * value
            current = 0
        else:
            current += value
    return str(total + current)


def _value(n) -> str:
    """The value of a scanned number with its magnitude word applied: 50 thousand -> '50000'."""
    if not n.get("mag"):
        return n["num"]
    try:
        value = float(n["num"]) * MAG_SCALE[n["mag"]]
    except ValueError:
        return n["num"] + " " + n["mag"]
    return str(int(value)) if value == int(value) else repr(value)


def _numbers_of(text: str, ctx, quote_side=False):
    masked, dates = _mask_dates(_plain(text))
    return _scan_numbers(re.sub(r"\s+", " ", masked), ctx, quote_side), dates


def _cells(row: str) -> list:
    s = (row or "").strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    return [c.strip() for c in re.split(r"(?<!\\)\|", s)]


def _is_row(quote: str) -> bool:
    return (quote or "").lstrip().startswith("|")


def _absolute_re(words):
    alt = "|".join(r"\s+".join(re.escape(p) for p in w.split()) for w in sorted(words, key=len, reverse=True))
    return re.compile(r"(?<![A-Za-z0-9-])(?:" + alt + r")(?![A-Za-z0-9-])", re.I)


