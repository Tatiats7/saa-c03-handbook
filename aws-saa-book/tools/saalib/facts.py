def _hand_files():
    """(chapter id, path) of every hand-written Markdown file of every chapter."""
    mark = ((_spec().get("generated_regions") or {}).get("generated_file_first_line") or DEFAULT_MARK).strip()
    for ch in common.chapters():
        folder = common.BOOK / f"{ch['id']}-{ch['slug']}"
        if not folder.is_dir():
            continue
        for path in sorted(folder.glob("*.md")):
            try:
                with open(path, encoding="utf-8") as handle:
                    first = handle.readline().strip()
            except OSError:
                continue
            if first != mark and not first.startswith("<!-- generated by saa.py"):
                yield ch["id"], path


def _item_files():
    """(chapter id, kind, path) of every chapter item file."""
    if not common.DATA.is_dir():
        return
    for folder in sorted(common.DATA.iterdir()):
        if folder.is_dir() and re.match(r"^\d{2}-", folder.name):
            for kind in ITEM_KINDS:
                path = folder / f"{kind}.json"
                if path.exists():
                    yield folder.name[:2], kind, path


def _items_of(doc) -> list:
    items = doc.get("items") if isinstance(doc, dict) else doc
    return [i for i in items or [] if isinstance(i, dict)]


def _item_fact_ids(item) -> set:
    ids = set(item.get("facts") or []) | set(item.get("cost_facts") or [])
    for key in ("key_points", "follow_ups"):
        for sub in item.get(key) or []:
            if isinstance(sub, dict):
                ids.update(sub.get("facts") or [])
    for sub in item.get("must_not_say") or []:
        if isinstance(sub, dict) and sub.get("fact"):
            ids.add(sub["fact"])
    return {i for i in ids if isinstance(i, str)}


_RE_ANY_LINK = re.compile(r"\]\(\.\./facts/([a-z0-9-]+)\.md#([a-z0-9-]+)\)")


def _walk(node, fn):
    if isinstance(node, str):
        return fn(node)
    if isinstance(node, list):
        return [_walk(n, fn) for n in node]
    if isinstance(node, dict):
        return {k: _walk(v, fn) for k, v in node.items()}
    return node


def _effects(fact, reason, mapping=None, new_displays=None, new_fact=None, relink=False, reset=True,
             dry=False, stale=True, log=None) -> dict:
    """Find the dependents of a fact (TOOLS.md 5.7) and apply steps 1 to 4.

    mapping: {old display: new display} for link texts; new_displays: normalised displays a link text must hold
    after the change (others are reported as broken); new_fact with relink: rewrite links and fact lists.
    """
    fid, service = fact["id"], fact["service"]
    link_re = re.compile(r"\[([^\]\n]*)\]\(\.\./facts/" + re.escape(service) + r"\.md#" + re.escape(fid) + r"\)")
    tail = f"facts/{service}.md#{fid})"
    target = f"../facts/{new_fact['service']}.md#{new_fact['id']}" if (relink and new_fact) else f"../facts/{service}.md#{fid}"
    mapping = {k: v for k, v in (mapping or {}).items() if k and k != v}
    lookup = {k.lower(): v for k, v in mapping.items()}
    map_re = re.compile("|".join(re.escape(k) for k in sorted(mapping, key=len, reverse=True)), re.I) if mapping else None
    state = {"replaced": 0, "broken": []}

    def rewrite(text):
        def sub(m):
            old = new = m.group(1)
            if map_re:
                norm = common.normalize_text(old)

                def swap(k):
                    value = lookup[k.group(0).lower()]
                    return k.group(0) if common.normalize_text(value) in norm else value
                new = map_re.sub(swap, old)
                if new != old:
                    state["replaced"] += 1
            if new_displays is not None and not any(d and d in common.normalize_text(new) for d in new_displays):
                state["broken"].append(new)
            return f"[{new}]({target})"
        return link_re.sub(sub, text)

    deps = {"markdown": [], "questions": [], "cards": [], "speak": [], "tasks": []}
    chapters = {}
    change_text = bool(map_re) or (relink and new_fact is not None)
    for ch, path in _hand_files():
        text = path.read_text(encoding="utf-8")
        if tail not in text:
            continue
        chapters.setdefault(ch, set())
        for number, line in enumerate(text.splitlines(), 1):
            if tail in line:
                deps["markdown"].append({"file": _rel(path), "line": number})
        new_text = rewrite(text) if (change_text or new_displays is not None) else text
        if change_text and new_text != text and not dry:
            path.write_text(new_text, encoding="utf-8")
    for ch, kind, path in _item_files():
        with common.file_lock(path):
            try:
                doc = common.read_json(path)
            except ValueError:
                continue
            dirty = False
            for item in _items_of(doc):
                if fid not in _item_fact_ids(item) and tail not in json.dumps(item, ensure_ascii=False):
                    continue
                deps[kind].append(item.get("id"))
                chapters.setdefault(ch, set())
                if change_text or new_displays is not None:
                    fresh = _walk(item, rewrite)
                    if relink and new_fact is not None:
                        fresh = _walk(fresh, lambda s: new_fact["id"] if s == fid else s)
                    if change_text and fresh != item:
                        item.clear()
                        item.update(fresh)
                        dirty = True
                if reset and item.get("status") not in ("rejected", "retired"):
                    chapters[ch].add(kind)
                    before = (item.get("status"), item.get("verification"))
                    item["status"] = "candidate"
                    if kind == "questions":
                        item["verification"] = {"status": "candidate", "round": 0, "solvers": []}
                    dirty = dirty or before != (item.get("status"), item.get("verification"))
            if dirty and not dry:
                common.write_json(path, doc)
    terms = []
    try:
        for term in (common.read_json(common.DATA / "terms.json", {}) or {}).get("terms", []):
            if fid in (term.get("facts") or []):
                terms.append(term.get("id"))
    except (ValueError, AttributeError):
        pass
    if not dry:
        if stale:
            for ch, stages in sorted(chapters.items()):
                _mark_stale(ch, reason, item_stages=sorted(stages) if reset else None)
        if log is not None:
            common.append_jsonl(common.REPORTS / "changelog.jsonl",
                                dict(log, date=common.today(), fact=fid, reason=log.get("reason", reason),
                                     chapters=sorted(chapters)))
    return {"dependents": deps, "replaced": state["replaced"], "broken_links": state["broken"],
            "chapters": sorted(chapters), "terms": terms}


def _chapter_refs(ch_id: str):
    """(set of fact ids that the chapter's hand files and items link or list, files read)."""
    ids, files = set(), []
    for ch, path in _hand_files():
        if ch != ch_id:
            continue
        files.append(path)
        ids.update(m.group(2) for m in _RE_ANY_LINK.finditer(path.read_text(encoding="utf-8")))
    for ch, _kind, path in _item_files():
        if ch != ch_id:
            continue
        files.append(path)
        try:
            doc = common.read_json(path)
        except ValueError:
            continue
        for item in _items_of(doc):
            if item.get("status") in ("rejected", "retired"):
                continue
            ids |= _item_fact_ids(item)
            ids.update(m.group(2) for m in _RE_ANY_LINK.finditer(json.dumps(item, ensure_ascii=False)))
    return ids, files


