_RE_UNSAFE = re.compile(r"[^A-Za-z0-9._~-]")


def _snap_base(source_id):
    sid = (source_id or "").strip() if isinstance(source_id, str) else ""
    parts = sid.split("/")
    if not sid or len(parts) < 2 or any(p in ("", ".", "..") or _RE_UNSAFE.search(p) for p in parts):
        return None
    return str(common.CORPUS / "snap" / sid)


def _corpus():
    try:
        from . import corpus
        return corpus
    except Exception:
        return None


def _source_for_url(url: str):
    """The source_id of a saved snapshot of this URL (TOOLS.md section 0, rule 11), or None."""
    corpus = _corpus()
    if corpus is not None:
        try:
            sid = corpus.source_id_for(url)
            base = _snap_base(sid)
            if base and Path(base + ".txt").exists():
                return sid
        except Exception:
            pass
    snap = common.CORPUS / "snap"
    if snap.is_dir():
        for meta_path in sorted(snap.rglob("*.meta.json")):
            try:
                meta = common.read_json(meta_path) or {}
            except ValueError:
                continue
            if meta.get("url") == url:
                return meta.get("source_id") or str(meta_path.relative_to(snap))[:-len(".meta.json")]
    return None


