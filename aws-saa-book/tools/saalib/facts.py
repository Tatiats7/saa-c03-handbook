def _audit_path(name: str) -> Path:
    stem = Path(name).stem if name.endswith(".json") else name
    return common.REPORTS / "audit" / f"{stem}.json"


@_guard
def cmd_audit_sample(args) -> int:
    pool = sorted((f for f in load().values() if f.get("status") == "verified" and f.get("hard")), key=lambda f: f["id"])
    first = []
    if args.chapter:
        ch = common.chapter(args.chapter)["id"]
        pool = [f for f in pool if f.get("home_chapter") == ch]
        first = [f for f in pool if f.get("tier0")][:args.n]
    rest = [f for f in pool if f not in first]
    sample = first + random.Random(args.seed).sample(rest, min(len(rest), max(0, args.n - len(first))))
    corpus, errors = _corpus(), []
    if args.revalidate and corpus is not None:
        for sid, url in sorted({(e["source_id"], e["url"]) for f in sample for e in f["evidence"]}):
            try:
                corpus.fetch(url, revalidate=True, source_id=sid)
            except Exception as exc:
                errors.append(f"{url}: {exc}")
    ctx = _Ctx()
    rows, bad = [], []
    for fact in sample:
        findings = mech_check(fact, ctx)
        if findings:
            bad.append({"id": fact["id"], "errors": findings})
        rows.append({"id": fact["id"], "rev": fact["rev"], "claim": fact["claim"], "quote": fact["evidence"][0]["quote"],
                     "url": fact["evidence"][0]["url"], "mech_ok": not findings})
    name = f"s{args.seed}-n{args.n}"
    report = {"id": name, "seed": args.seed, "n": args.n, "created": common.now_iso(), "facts": rows}
    common.write_json(_audit_path(name), report)
    lines = [f"{'ok  ' if r['mech_ok'] else 'FAIL'} {r['id']}: {r['claim']}  <=  {_one_line(r['quote'])[:160]}" for r in rows]
    lines += [f"fetch error: {e}" for e in errors]
    _out(args, dict(report, report=_rel(_audit_path(name)), mech_failed=bad),
         f"audit sample {name}: {len(rows)} facts, {len(bad)} fail the mechanical checks; {_rel(_audit_path(name))}", lines)
    return common.EXIT_FAIL if bad else common.EXIT_OK


def _audit(name) -> dict:
    report = common.read_json(_audit_path(name))
    if not report:
        raise _Stop(f"no audit {name}; run: saa.py audit sample --n N --seed S", common.EXIT_PRECONDITION)
    return report


@_guard
def cmd_audit_packet(args) -> int:
    report = _audit(args.audit)
    common.emit(_packet(report["id"], "rederive", [f["id"] for f in report["facts"]], _Ctx()), args)
    return common.EXIT_OK


@_guard
def cmd_audit_result(args) -> int:
    report = _audit(args.audit)
    canon = load()
    match, failed, waiting = 0, [], []
    for row in report["facts"]:
        fact = canon.get(row["id"])
        votes = [v for v in _votes(fact["service"]) if v.get("fact") == row["id"] and v.get("lens") == "rederive"
                 and v.get("rev") == row["rev"]] if fact else []
        if not votes:
            waiting.append(row["id"])
        elif all(v.get("verdict") == "match" for v in votes):
            match += 1
        else:
            failed.append(row["id"])
    expand = sorted({canon[i]["home_chapter"] for i in failed if i in canon}) if len(failed) >= 2 else []
    result = {"sample": len(report["facts"]), "match": match, "failed": failed, "expand": expand}
    _out(args, result, f"audit result {report['id']}: {match} of {result['sample']} match, {len(failed)} failed, "
                       f"{len(waiting)} without a vote",
         [f"failed: {i}" for i in failed] + [f"no vote: {i}" for i in waiting] + [f"re-derive every hard fact of chapter {c}" for c in expand])
    if len(failed) >= 2:
        return common.EXIT_FAIL
    return common.EXIT_WARN if (failed or waiting) else common.EXIT_OK


