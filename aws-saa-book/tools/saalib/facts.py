def _rederive_verdict(fact, vote, ctx) -> str:
    answer = vote.get("answer")
    if answer is None:
        return "not-found"
    snap = ctx.snap(vote.get("source_id")) if vote.get("source_id") else None
    quote = vote.get("quote") or ""
    if snap is None or not quote or common.find_quote(quote, snap["norm"], already_normalized=True) is None:
        return "mismatch"
    found = {n["num"] for n in _numbers_of(f"{answer} ; {quote}", ctx, quote_side=True)[0]}
    wanted = set()
    for value in fact.get("values") or []:
        wanted.update(n["num"] for n in _numbers_of(value.get("display") or "", ctx)[0])
    if wanted:
        return "match" if wanted <= found else "mismatch"
    hay = (common.normalize_text(str(answer)), common.normalize_text(quote))
    return "match" if any(d and (_holds(hay[0], d) or _holds(hay[1], d)) for d in displays(fact)) else "mismatch"


@_guard
def cmd_vote(args) -> int:
    label = _label(args, required=True)
    rows = _input_list(args.file)
    canon, ctx = load(), _Ctx()
    try:
        from . import schemas
    except ImportError:
        schemas = None
    accepted, refused = [], []
    me, logs, seen = voter_key(label), {}, set()
    for raw in rows:
        fid = raw.get("fact")
        fact = canon.get(fid)
        problems = []
        vote = {"fact": fid, "rev": raw.get("rev"), "lens": raw.get("lens"), "verdict": raw.get("verdict"), "voter": label,
                "ts": common.now_iso(), "batch": raw.get("batch"), "reason": raw.get("reason"),
                "source_id": raw.get("source_id"), "quote": raw.get("quote"), "answer": raw.get("answer")}
        if fact is None:
            problems.append("unknown fact")
        else:
            if vote["rev"] != fact.get("rev"):
                problems.append(f"rev {vote['rev']} is not the current rev {fact.get('rev')}")
            vote["content"] = content_hash(fact)
            if me in _writers(fact):
                problems.append("the author of a fact, or an agent that amended it, cannot vote on it")
            if vote["lens"] in ONCE_LENSES:
                service = fact["service"]
                if service not in logs:
                    logs[service] = _votes(service)
                key = (fid, vote["rev"], vote["lens"])
                if key in seen or any(voter_key(v.get("voter")) == me and (v.get("fact"), v.get("rev"), v.get("lens")) == key
                                      and v.get("content") == vote["content"] for v in logs[service]):
                    problems.append(f"voter {label!r} has already voted on this fact, rev and lens; a vote is not replaced "
                                    "(a disputed fact needs `facts amend`)")
                seen.add(key)
            if fact.get("status") in ("rejected", "superseded"):
                problems.append(f"the fact is {fact.get('status')}")
            if vote["quote"]:
                snap = ctx.snap(vote["source_id"]) if vote["source_id"] else None
                if snap is None or common.find_quote(vote["quote"], snap["norm"], already_normalized=True) is None:
                    problems.append(f"the quote is not in the snapshot {vote['source_id']!r}")
            if vote["lens"] == "rederive" and not problems:
                vote["verdict"] = _rederive_verdict(fact, vote, ctx)
        if vote["lens"] not in LENS_VERDICTS:
            problems.append(f"unknown lens {vote['lens']!r}")
        elif vote["verdict"] not in LENS_VERDICTS[vote["lens"]] and not problems:
            problems.append(f"verdict {vote['verdict']!r} is not allowed for lens {vote['lens']}")
        if not problems and schemas is not None:
            problems += schemas.validate(vote, "vote")
        if problems:
            refused.append({"fact": fid, "errors": [_finding("V01", p, item=fid if isinstance(fid, str) else None) for p in problems]})
        else:
            accepted.append((fact, vote))
    if refused:
        _out(args, {"appended": 0, "refused": refused}, f"facts vote: refused, nothing appended ({len(refused)} bad votes)",
             [_text_finding(f) for r in refused for f in r["errors"]])
        return common.EXIT_FAIL
    disputed, changes = [], {}
    for fact, vote in accepted:
        common.append_jsonl(_votes_path(fact["service"]), vote)
        if vote["lens"] == "rederive" and vote["verdict"] != "match" and fact.get("status") == "verified":
            def dispute(row):
                row["status"] = "disputed"
            changes[fact["id"]] = (fact["service"], dispute)
    if changes:
        _update_facts(changes)
        for fid in sorted(changes):
            disputed.append(fid)
            for ch in _effects(canon[fid], "", reset=False, dry=True)["chapters"]:
                _mark_stale(ch, f"fact {fid} failed a re-derivation")
    result = {"appended": len(accepted), "refused": [], "disputed": disputed,
              "verdicts": [{"fact": v["fact"], "lens": v["lens"], "verdict": v["verdict"]} for _f, v in accepted]}
    _out(args, result, f"facts vote: {len(accepted)} appended" + (f", {len(disputed)} facts now disputed" if disputed else ""),
         [f"{v['fact']} {v['lens']} {v['verdict']}" for _f, v in accepted])
    return common.EXIT_OK


@_guard
def cmd_finalize(args) -> int:
    chosen = {f["id"] for f in _select(args)}
    result = {"verified": [], "disputed": [], "rejected": [], "pending": []}
    conflicted = _open_conflict_ids()
    for service in _services():
        path = fact_path(service)
        with common.file_lock(path):
            rows = _rows(service)
            if not any(r["id"] in chosen and r.get("status") in ("mech-pass", "disputed") for r in rows):
                continue
            votes, ctx, dirty = _votes(service), _Ctx(), False
            for fact in rows:
                if fact["id"] not in chosen or fact.get("status") not in ("mech-pass", "disputed"):
                    continue
                outcome, missing, counting = _decide(fact, votes, conflicted)
                summary = [{"lens": v["lens"], "verdict": v["verdict"], "voter": v["voter"], "rev": v["rev"]} for v in counting]
                if outcome == "verified":
                    findings = mech_check(fact, ctx)
                    if findings:      # never verify what the mechanical checks no longer accept
                        fact.update(status="candidate", stale="mech-failed", mech=_mech_record(findings))
                        result["pending"].append({"id": fact["id"], "missing": ["mech"]})
                        dirty = True
                        continue
                if outcome == "pending":
                    result["pending"].append({"id": fact["id"], "missing": missing})
                    continue
                result[outcome].append(fact["id"])
                if fact.get("status") != outcome or fact.get("votes") != summary:
                    fact.update(status=outcome, votes=summary)
                    dirty = True
            if dirty:
                _save(service, rows)
    lines = [f"{k}: {i}" for k in ("disputed", "rejected") for i in result[k]]
    lines += [f"pending: {p['id']} (missing {', '.join(p['missing'])})" for p in result["pending"]]
    _out(args, result, "facts finalize: " + ", ".join(f"{len(result[k])} {k}" for k in result), lines)
    if result["disputed"] or result["rejected"]:
        return common.EXIT_FAIL
    return common.EXIT_WARN if result["pending"] else common.EXIT_OK


