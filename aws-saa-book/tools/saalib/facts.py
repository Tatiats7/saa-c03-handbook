def _out(args, obj, summary, lines=()):
    if getattr(args, "json", False):
        common.emit(obj, args)
        return
    lines = list(lines)
    if not getattr(args, "out", None) and len(lines) > 40:
        lines = lines[:40] + [f"... ({len(lines) - 40} more lines; use --out FILE or --json)"]
    common.emit("\n".join([summary] + lines), args)


def _label(args, required=False) -> str:
    label = (getattr(args, "by", None) or os.environ.get("SAA_AGENT") or "unknown").strip() or "unknown"
    if required and label == "unknown":
        raise _Stop("this command needs --by LABEL (or the environment variable SAA_AGENT)", common.EXIT_PRECONDITION)
    return label


def _input(path_text):
    path = Path(path_text)
    if not path.is_absolute():
        path = common.REPO / path
    if not common.inside_book(path):
        raise _Stop(f"--file must be inside {common.REAL_BOOK}", common.EXIT_POLICY)
    if not path.exists():
        raise _Stop(f"file not found: {path_text}", common.EXIT_PRECONDITION)
    try:
        data = common.read_json(path)
    except ValueError as exc:
        raise _Stop(f"{path_text} is not valid JSON: {exc}", common.EXIT_FAIL)
    return data


def _input_list(path_text) -> list:
    data = _input(path_text)
    rows = data if isinstance(data, list) else [data]
    if not rows or not all(isinstance(r, dict) for r in rows):
        raise _Stop("--file must hold one JSON object or an array of objects", common.EXIT_FAIL)
    return rows


def _select(args, ctx=None) -> list:
    """(service, id) pairs chosen by ID ..., --service, --chapter or --all (default: all)."""
    canon = {}
    for service in _services():
        for row in _rows(service):
            canon[row["id"]] = row
    ids = list(getattr(args, "ids", None) or [])
    if ids:
        missing = [i for i in ids if i not in canon]
        if missing:
            raise _Stop(f"unknown fact: {', '.join(missing)}", common.EXIT_PRECONDITION)
        return [canon[i] for i in ids]
    facts = sorted(canon.values(), key=lambda f: f["id"])
    if getattr(args, "service", None):
        facts = [f for f in facts if f.get("service") == args.service]
    if getattr(args, "chapter", None):
        ch = common.chapter(args.chapter)["id"]
        facts = [f for f in facts if f.get("home_chapter") == ch]
    return facts


def _update_facts(changes: dict) -> None:
    """Apply {fact id: function(fact)} under the lock of each fact file; a function mutates the stored row."""
    by_service = collections.defaultdict(dict)
    for fid, (service, fn) in changes.items():
        by_service[service][fid] = fn
    for service in sorted(by_service):
        path = fact_path(service)
        with common.file_lock(path):
            rows = _rows(service)
            for row in rows:
                if row["id"] in by_service[service]:
                    by_service[service][row["id"]](row)
            _save(service, rows)


def _guard(func):
    def wrapped(args):
        try:
            return func(args)
        except _Stop as stop:
            return common.fail(str(stop), stop.code)
    wrapped.__name__ = func.__name__
    return wrapped


