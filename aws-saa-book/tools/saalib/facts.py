def _scope_line(fact) -> str:
    q = fact.get("qualifiers") or {}
    parts = [str(q.get("scope") or "").strip(),
             {"default": "default", "max": "maximum", "min": "minimum", "fixed": "fixed"}.get(q.get("default_or_max"), "")]
    if fact.get("kind") in QUALIFIED_KINDS:
        parts.append("adjustable" if q.get("adjustable") else "not adjustable")
    parts.append(str(q.get("condition") or "").strip())
    parts = [p for p in parts if p]
    return "; ".join(parts) + "." if parts else ""


def _one_line(text: str) -> str:
    return re.sub(r"\s+", " ", text or "").strip()


def _sheet_title(service: str) -> str:
    try:
        registry = common.read_json(common.REGISTRY / "services.json", {}) or {}
    except ValueError:
        registry = {}
    for entry in registry.get("in_scope") or []:
        if service in (entry.get("keys") or []):
            return entry.get("official_name") or service
    return service


def render_sheet(service: str):
    """Markdown of facts/<service>.md, or None when the service has no verified or superseded fact."""
    facts = sorted((f for f in _rows(service) if f.get("status") in ("verified", "superseded")), key=lambda f: f["id"])
    if not facts:
        return None
    mark = ((_spec().get("generated_regions") or {}).get("generated_file_first_line") or DEFAULT_MARK).strip()
    live = [f for f in facts if f["status"] == "verified"]
    newest = max((f.get("retrieved") or "" for f in live), default="") or max(f.get("retrieved") or "" for f in facts)
    count = f"{len(live)} fact{'' if len(live) == 1 else 's'}"
    blocks = [f"{mark}\n# {_sheet_title(service)}: facts", f"{count}, each with the exact sentence from AWS. Last checked {newest}."]
    for fact in facts:
        blocks.append(f"### {fact['id']}")
        if fact["status"] == "superseded":
            new = fact.get("superseded_by") or ""
            blocks.append(f"Replaced by [{new}](#{new}).")
            continue
        blocks.append(f"**Claim.** {_one_line(fact['claim'])}")
        blocks.append("**Write it as.** " + " · ".join(f"`{v['display']}`" for v in fact["values"]))
        scope = _scope_line(fact)
        if scope:
            blocks.append(f"**Scope.** {scope}")
        for ev in fact["evidence"]:
            quote = _link_text(_one_line(ev["quote"]))
            if _is_row(quote):
                line = f'> "{" | ".join(_cells(quote))}" (columns: {" | ".join(_cells(ev.get("table_header") or ""))})'
            elif ev.get("heading"):
                line = f'> {_link_text(_one_line(ev["heading"]))}: "{quote}"'
            else:
                line = f'> "{quote}"'
            blocks.append(f"{line}\n> — [{ev.get('title') or ev['url']}]({ev['url']})")
        blocks.append(f"**Checked.** {fact.get('retrieved')}.")
        if fact.get("changed"):
            blocks.append(f"**Changed.** {fact['changed']['date']}: was {fact['changed']['was']}.")
    return "\n\n".join(blocks) + "\n"


def _card(fact) -> dict:
    card = {"id": fact["id"], "status": fact["status"], "claim": fact["claim"], "scope": _scope_line(fact),
            "links": [f"[{v['display']}](../facts/{fact['service']}.md#{fact['id']})" for v in fact["values"]],
            "spoken": [v["spoken"] for v in fact["values"] if v.get("spoken")], "changed": None}
    if fact.get("changed"):
        card["changed"] = f"{fact['changed']['date']}: was {fact['changed']['was']}"
    return card


