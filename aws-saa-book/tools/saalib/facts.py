def voter_key(label) -> str:
    """Labels are compared without case, spaces and punctuation: `Miner-A`, `miner_a` and `miner a` are one voter."""
    return re.sub(r"[^a-z0-9]+", "", unicodedata.normalize("NFKC", str(label or "")).lower())


def _hash_evidence(ev) -> dict:
    out = {k: ev.get(k) for k in EVIDENCE_KEYS}
    if ev.get("heading") is not None:          # only when set, so the hash of every other fact stays the same
        out["heading"] = ev["heading"]
    return out


def content_hash(fact) -> str:
    """SHA-256 of the parts of a fact that a vote judges. `facts vote` stores it in the vote."""
    body = {k: fact.get(k) for k in CONTENT_KEYS}
    body["evidence"] = [_hash_evidence(e) for e in fact.get("evidence") or [] if isinstance(e, dict)]
    return common.sha256_bytes(json.dumps(body, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8"))


def _writers(fact) -> set:
    """voter keys of the agents that wrote the current text of the fact: the author and everyone who amended it."""
    labels = [fact.get("author")] + list(fact.get("amended_by") or [])
    return {voter_key(x) for x in labels if x} - {""}


def _counting(fact, votes) -> list:
    """Votes that count: current rev, bound to the current content, not by the author or an amender.

    Every such vote counts (not only the last one of a voter), so a later line cannot cancel a negative vote.
    """
    writers, want, out = _writers(fact), None, []
    for v in votes:
        if v.get("fact") != fact["id"] or v.get("rev") != fact.get("rev"):
            continue
        if voter_key(v.get("voter")) in writers:
            continue
        if want is None:
            want = content_hash(fact)
        if v.get("content") != want:
            continue
        out.append(v)
    return out


def _decide(fact, votes, conflicted=()):
    """Outcome by the rules of TOOLS.md 5.4: (verified|disputed|rejected|pending, missing lenses, counting votes)."""
    counting = _counting(fact, votes)
    if fact["id"] in conflicted:
        return "disputed", [], counting
    if any(v.get("verdict") != POSITIVE.get(v.get("lens")) for v in counting):
        return ("rejected" if fact.get("repairs") == 1 else "disputed"), [], counting
    have = {v.get("lens") for v in counting}
    missing = [lens for lens in required_lenses(fact) if lens not in have]
    if missing:
        return "pending", missing, counting
    return "verified", [], counting


def _backing(fact, votes) -> list:
    """F04: a `verified` status that the vote log does not produce was not set by `facts finalize`."""
    if fact.get("status") != "verified":
        return []
    outcome, missing, _ = _decide(fact, votes)
    if outcome == "verified":
        return []
    why = f"no counting vote for {', '.join(missing)}" if missing else "a counting vote is not positive"
    return [_finding("F04", f"status verified is not backed by the vote log at rev {fact.get('rev')} ({why}); "
                            "the status was edited by hand", item=fact["id"])]


