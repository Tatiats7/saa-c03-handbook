def _locate(snap, ctx, quote):
    """Line range (first, last) of the snapshot that holds the quote, or None."""
    q = common.normalize_text(quote)
    lines = ctx.norm_lines(snap)
    for i, line in enumerate(lines):
        if q and q in line:
            return i, i
    head = " ".join(q.split()[:5])
    for i, line in enumerate(lines):
        if head and head in line:
            for j in range(i, min(i + 15, len(lines))):
                if q in common.normalize_text("\n".join(snap["lines"][i:j + 1])):
                    return i, j
    return None


def _context(snap, ctx, quote, line=None) -> dict:
    span = (line, line) if line is not None else _locate(snap, ctx, quote)
    if span is None:
        return {"context": "", "headings": []}
    first, last = span
    a, b = max(0, first - 5), min(len(snap["lines"]), last + 6)
    text = "\n".join(snap["lines"][a:b])
    while len(text) > 1500 and (a < first or b > last + 1):
        a, b = min(first, a + 1), max(last + 1, b - 1)
        text = "\n".join(snap["lines"][a:b])
    stack = []
    for line in snap["lines"][:first]:
        m = _RE_HEADING.match(line)
        if m:
            level = len(m.group(1))
            stack = [h for h in stack if h[0] < level] + [(level, _one_line(_plain(m.group(2)))[:120])]
    return {"context": text[:1500], "headings": [h[1] for h in stack]}


def _change_items(fact) -> list:
    try:
        from . import feeds
        rows = feeds.changes_for(fact["service"], since=str(_book_meta().get("change_window_start") or ""))
    except BaseException as exc:
        if isinstance(exc, KeyboardInterrupt):
            raise
        return []
    named = set(fact.get("change_items") or [])
    words = {w for w in re.findall(r"[a-z]+", (fact.get("claim") or "").lower()) if len(w) > 3}
    picked = []
    for row in rows:
        key = row.get("id") or f"{row.get('history_source_id')}#{row.get('line')}"
        text = " ".join(str(row.get(k, "")) for k in ("title", "summary")).lower()
        shared = words & {w for w in re.findall(r"[a-z]+", text) if len(w) > 3}
        if key in named or len(shared) >= 2:
            picked.append((key not in named, {"key": key, "date": row.get("date"), "title": row.get("title"),
                                              "summary": row.get("summary"), "url": row.get("url"), "quote": row.get("quote")}))
    picked.sort(key=lambda p: p[0])
    return [p[1] for p in picked[:8]]


def _packet_fact(fact, lens, ctx) -> dict:
    if lens == "rederive":
        return {"id": fact["id"], "rev": fact["rev"], "service": fact["service"], "question": fact.get("question")}
    out = {"id": fact["id"], "rev": fact["rev"], "kind": fact["kind"], "claim": fact["claim"], "values": fact["values"],
           "qualifiers": fact["qualifiers"], "derivation": fact.get("derivation"), "evidence": []}
    for ev in fact["evidence"]:
        snap = ctx.snap(ev.get("source_id"))
        line = _heading_scope(ev["quote"], ev["heading"], ctx, snap)[0] if snap and ev.get("heading") is not None else None
        where = _context(snap, ctx, ev["quote"], line) if snap else {"context": "", "headings": []}
        item = {"url": ev["url"], "title": ev.get("title"), "quote": ev["quote"], "table_header": ev.get("table_header")}
        if ev.get("heading") is not None:
            item["heading"] = ev["heading"]
        out["evidence"].append(dict(item, **where))
    if lens == "currency":
        out["change_items"] = _change_items(fact)
    return out


