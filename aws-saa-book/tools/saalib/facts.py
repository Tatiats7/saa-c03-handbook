def is_volatile(fact) -> bool:
    if fact.get("volatility") == "frequently-changing" or fact.get("kind") == "price":
        return True
    changed = fact.get("changed")
    if not changed or not changed.get("date"):
        return False
    months = int((_spec().get("questions") or {}).get("volatile_window_months", 24))
    snap = str(_book_meta().get("snapshot_date") or common.today())
    year, month, day = int(snap[:4]), int(snap[5:7]), int(snap[8:10] or 1)
    total = year * 12 + (month - 1) - months
    cut = f"{total // 12:04d}-{total % 12 + 1:02d}-{day:02d}"
    date = changed["date"]
    return date >= cut if len(date) > 7 else date >= cut[:7]


def required_lenses(fact) -> list:
    # Every fact needs an entail vote (gate-break H1, H9): the author sets `hard`, so `hard` cannot switch the
    # only check that ties the claim to the quote off. `hard` still decides M13 and the audit sample.
    need = ["entail"]
    if fact.get("changed") or fact.get("change_items") or fact.get("volatility", "stable") != "stable":
        need.append("currency")
    derivation = fact.get("derivation")
    if isinstance(derivation, str) and derivation.strip():
        need.append("derive")
    return need


