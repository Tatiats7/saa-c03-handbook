def _check_m1(fact, ctx, new):
    out = []
    try:
        from . import schemas
        for err in schemas.validate(fact, "fact"):
            out.append(("M1", f"schema: {err}"))
    except ImportError:
        pass
    fid, service = fact.get("id"), fact.get("service")
    if not isinstance(fid, str) or not isinstance(service, str):
        return out
    if not fid.startswith(service + "-"):
        out.append(("M1", f"id does not start with '{service}-'"))
    count = ctx.id_count.get(fid, 0)
    if (new and count >= 1) or count > 1:
        out.append(("M1", f"id {fid} is already in the canon; a fact id is never reused"))
    if service not in ctx.keys:
        out.append(("M1", f"service {service!r} is no chapter service key and no fact namespace"))
    elif fact.get("home_chapter") != ctx.keys[service]:
        out.append(("M1", f"home_chapter must be {ctx.keys[service]} for service {service}"))
    for other in ctx.keys:
        if len(other) > len(service) and fid.startswith(other + "-"):
            out.append(("M1", f"id starts with the longer key '{other}-'; the fact belongs to {other}"))
    return out


def _complete_sentence(q: str, ctx, snap) -> bool:
    if not q.endswith("."):
        return False
    for line in ctx.norm_lines(snap):
        at = line.find(q)
        while at >= 0:
            before, after = line[:at].rstrip(), line[at + len(q):]
            if (at == 0 or before[-1:] in ".?!:") and (after == "" or after[0] == " "):
                return True
            at = line.find(q, at + 1)
    return False


def _provenance(source_id, snap):
    """Why a snapshot is no evidence (gate-break H5), or None. Only `saa.py fetch` makes a snapshot: it writes the
    .raw body, the .txt and a meta file with the SHA-256 of both, and one line in fetch.log.jsonl."""
    meta = snap["meta"] or {}
    if meta.get("fixture") is True:
        if Path(common.BOOK).resolve() == Path(common.REAL_BOOK).resolve():
            return "a fixture snapshot is no evidence in the real book"
        if meta.get("sha256") != snap["sha"]:
            return "the .txt of the fixture snapshot does not have the SHA-256 of its meta file"
        return None
    if not meta.get("text_sha256") or not meta.get("sha256"):
        return "the meta file has no fetch record (sha256, text_sha256); only `saa.py fetch` makes a snapshot"
    if meta["text_sha256"] != snap["sha"]:
        return "the .txt was changed after the fetch (run `saa.py fetch URL --reextract` or fetch the page again)"
    raw = Path(_snap_base(source_id) + ".raw")
    if not raw.exists() or common.sha256_file(raw) != meta["sha256"]:
        return "the .raw body of the fetch is missing or was changed"
    if "fetch_log" not in snap:
        log = common.CORPUS / "fetch.log.jsonl"
        snap["fetch_log"] = log.exists() and any(
            f'"{source_id}"' in line for line in log.read_text(encoding="utf-8", errors="replace").splitlines())
    if not snap["fetch_log"]:
        return "fetch.log.jsonl has no request for this snapshot"
    return None


_RE_ZERO_WIDTH = re.compile("[" + "".join(chr(c) for c in (0x200B, 0x200C, 0x200D, 0x2060, 0xFEFF, 0xAD)) + "]")


def _hidden_text(quote: str, snap) -> bool:
    """True when the stored quote holds text that the quote match ignores (gate-break H4): something in angle
    brackets, a link target, a list or heading prefix, or a line break, that is not literally on the page."""
    q = (quote or "").strip()
    risky = ("\n" in q or _RE_ZERO_WIDTH.search(q) or _RE_TAG.search(html.unescape(q)) or _RE_IMG.search(q)
             or _RE_LINK.search(q) or re.search(r"\[[^\]]+\]\[[^\]]*\]", q)
             or re.match(r"\s{0,8}(?:#{1,6}\s+|[+\-*]\s+|\d{1,3}[.)]\s+|>\s?)", q))
    return bool(risky) and q not in snap["text"]


def _placement(q: str, ctx, snap):
    """Where the normalised quote stands on the page: (whole sentences?, crosses a heading?, table text?).
    None when the quote cannot be placed on the lines of the snapshot."""
    joined, spans = ctx.layout(snap)
    best, at = None, joined.find(q)
    while at >= 0:
        end = at + len(q)
        touched = [(a, b, kind) for a, b, kind in spans if a < end and b > at]
        before = joined[:at].rstrip().rstrip("\"')]")
        starts = any(a == at for a, _b, _k in touched) or before[-1:] in (".", "?", "!", ":")
        ends = any(b == end for _a, b, _k in touched) or (
            q.rstrip("\"')]")[-1:] in (".", "?", "!", ":") and joined[end:end + 1] == " ")
        heading = len(touched) > 1 and any(kind == "heading" for _a, _b, kind in touched)
        table = any(kind == "table" for _a, _b, kind in touched)
        found = (starts and ends, heading, table)
        if found == (True, False, False):
            return found
        best = best or found
        at = joined.find(q, at + 1)
    return best


def _row_header_ok(ev, snap) -> bool:
    """When the row stands in a parsed table of the snapshot, the header must be the header of that table."""
    corpus = _corpus()
    if corpus is None:
        return True
    try:
        tables = corpus.parse_tables(snap["text"])
    except Exception:
        return True
    row = common.normalize_text(ev["quote"])
    homes = [t for t in tables if any(common.normalize_text(r["text"]) == row for r in t["rows"])]
    if not homes:
        return True
    header = common.normalize_text(ev.get("table_header") or "")
    return any(common.normalize_text(t["header_text"]) == header for t in homes)


HEADING_WINDOW = 5      # a heading-scoped quote stands within the next 5 non-empty lines under its heading


def _heading_scope(quote: str, heading, ctx, snap):
    """M4 for an evidence item with `heading`: the quote is one whole line of the snapshot (1 to 80 words), `heading`
    is the nearest heading line above it, and the line is among the next HEADING_WINDOW non-empty lines.
    Returns (line index in snap["lines"], None) or (None, what to do)."""
    if not isinstance(heading, str) or not heading.strip():
        return None, "heading must be the text of a heading line of the snapshot"
    if _is_row(quote):
        return None, "a table-row quote takes table_header, not heading"
    q, h = common.normalize_text(quote), common.normalize_text(heading)
    words = len(q.split())
    if not 1 <= words <= 80:
        return None, f"a quote with heading is one line of 1 to 80 words; it has {words}"
    joined, spans = ctx.layout(snap)
    rows = [n for n, norm in enumerate(ctx.norm_lines(snap)) if norm]       # the line of each layout span
    if not any(kind == "heading" and joined[a:b] == h for a, b, kind in spans):
        return None, f"heading {heading!r} is not a heading line of the snapshot; copy the heading text as on the page"
    hits = [k for k, (a, b, _kind) in enumerate(spans) if joined[a:b] == q]
    if not hits:
        return None, ("a quote with heading must be one whole line of the snapshot, from line start to line end; "
                      "quote the whole value line")
    why = None
    for k in hits:
        top = next((j for j in range(k - 1, -1, -1) if spans[j][2] == "heading"), None)
        if spans[k][2] != "text":
            why = why or "the quoted line is a heading or a table row; quote the value line under the heading"
        elif top is None or joined[spans[top][0]:spans[top][1]] != h:
            why = why or f"heading {heading!r} is not the nearest heading above the quoted line; name that heading"
        elif k - top > HEADING_WINDOW:
            why = why or (f"the quoted line is non-empty line {k - top} under heading {heading!r}; "
                          f"a quote with heading must be within the first {HEADING_WINDOW}")
        else:
            return rows[k], None
    return None, why


def _check_evidence(fact, ctx):
    """M2, M3, M4 and M8 for every evidence item."""
    out = []
    for i, ev in enumerate(fact.get("evidence") or []):
        if not isinstance(ev, dict):
            continue
        url, quote = ev.get("url") or "", ev.get("quote") or ""
        try:
            parts = urllib.parse.urlsplit(url)
            host, scheme = (parts.hostname or "").lower(), parts.scheme
        except ValueError:
            host, scheme = "", ""
        if scheme != "https" or host not in common.ALLOWED_HOSTS:
            out.append(("M2", f"evidence {i}: host {host or url[:60]!r} is not in the allow-list"))
            continue
        snap = ctx.snap(ev.get("source_id"))
        if snap is None:
            out.append(("M2", f"evidence {i}: no snapshot {ev.get('source_id')!r} in the corpus"))
            continue
        if (snap["meta"] or {}).get("url") != url:
            out.append(("M2", f"evidence {i}: the snapshot was saved for {(snap['meta'] or {}).get('url')!r}, not for {url!r}"))
        if snap["sha"] != ev.get("sha256"):
            out.append(("M2", f"snapshot-changed: evidence {i}: the text of {ev.get('source_id')} has another SHA-256 now"))
        else:
            why = _provenance(ev.get("source_id"), snap)
            if why:
                out.append(("M2", f"evidence {i}: snapshot {ev.get('source_id')} is not a fetched page: {why}"))
        q = common.normalize_text(quote)
        if common.find_quote(quote, snap["norm"], already_normalized=True) is None:
            out.append(("M3", f"evidence {i}: the quote is not in the snapshot text (verbatim text only): {quote[:70]!r}"))
            continue
        if _hidden_text(quote, snap):
            out.append(("M3", f"evidence {i}: the quote holds markup, a list prefix or a line break that is not on the page; "
                              f"copy the text of one line exactly: {quote[:70]!r}"))
            continue
        words = len(q.split())
        place = None if _is_row(quote) else _placement(q, ctx, snap)
        if ev.get("heading") is not None:
            if ev.get("table_header"):
                out.append(("M4", f"evidence {i}: a quote with heading has no table_header"))
            else:
                why = _heading_scope(quote, ev["heading"], ctx, snap)[1]
                if why:
                    out.append(("M4", f"evidence {i}: {why}"))
        elif _is_row(quote):
            header = ev.get("table_header")
            if not header:
                out.append(("M4", f"evidence {i}: a table-row quote needs table_header (use `facts adopt --table --row`)"))
            elif common.find_quote(header, snap["norm"], already_normalized=True) is None:
                out.append(("M4", f"evidence {i}: table_header is not in the snapshot"))
            elif len(_cells(header)) != len(_cells(quote)):
                out.append(("M4", f"evidence {i}: table_header has {len(_cells(header))} cells, the row has {len(_cells(quote))}"))
            elif not _row_header_ok(ev, snap):
                out.append(("M4", f"evidence {i}: table_header is not the header row of the table that holds the row"))
        elif words > 80:
            out.append(("M4", f"evidence {i}: the quote has {words} words (at most 80)"))
        elif words < 4:
            out.append(("M4", f"evidence {i}: the quote has {words} words (at least 8, or 4 to 7 for one complete sentence; "
                              "a value line under a heading needs `heading`: use `facts adopt --heading`)"))
        elif words < 8 and not _complete_sentence(q, ctx, snap):
            out.append(("M4", f"evidence {i}: a quote of {words} words must be one complete sentence of the snapshot "
                              "(a value line under a heading needs `heading`: use `facts adopt --heading`)"))
        elif place is None:
            out.append(("M4", f"evidence {i}: the quote cannot be placed on whole lines of the snapshot; quote whole sentences "
                              "of one paragraph"))
        elif place[2]:
            out.append(("M4", f"evidence {i}: the quote is table text; quote one row with its table_header "
                              "(use `facts adopt --table --row`)"))
        elif not place[0]:
            out.append(("M4", f"evidence {i}: the quote must start at the start and end at the end of a sentence of the "
                              f"snapshot: {quote[:70]!r}"))
        if place and place[1]:
            out.append(("M8", f"evidence {i}: the quote runs across a heading"))
        hit = next((p for p in BOILERPLATE if p in q), None)
        if hit:
            out.append(("M8", f"evidence {i}: the quote is page furniture ({hit!r})"))
        elif any(_RE_HEADING.match(line) and nl == q
                 for line, nl in zip(snap["lines"], ctx.norm_lines(snap)) if line.lstrip().startswith("#")):
            out.append(("M8", f"evidence {i}: the quote is a single heading line"))
    return out


def _check_m5(fact, ctx):
    out, soft = [], []
    qnums, qdates, rows = [], [], []
    for ev in fact.get("evidence") or []:
        if not isinstance(ev, dict):
            continue
        row_nums = set()
        for part in (ev.get("quote"), ev.get("table_header")):
            if part:
                nums, dates = _numbers_of(part, ctx, quote_side=True)
                qnums += nums
                qdates += dates
                row_nums.update(n["num"] for n in nums)
        if _is_row(ev.get("quote") or ""):
            rows.append((_plain(ev["quote"]) + " | " + _plain(ev.get("table_header") or ""), row_nums))
    have = {_value(n) for n in qnums}
    have_units = {(n["num"], ctx.unit_key(n["unit"])) for n in qnums if n["unit"]}
    changed = fact.get("changed") if isinstance(fact.get("changed"), dict) else None
    targets = [("claim", fact.get("claim") or "")]
    targets += [(f"display {v.get('display')!r}", v.get("display") or "") for v in fact.get("values") or [] if isinstance(v, dict)]
    if changed:
        targets.append(("changed.was", changed.get("was") or ""))
    for label, text in targets:
        nums, dates = _numbers_of(text, ctx)
        for date in dates:
            if not ((changed and _date_eq(date, changed.get("date", ""))) or any(_date_eq(date, q) for q in qdates)):
                out.append(("M5", f"date {date} in {label} is not changed.date and stands in no quote"))
        for n in nums:
            if _value(n) not in have:
                shown = n["num"] + (f" {n['mag']}" if n.get("mag") else "")
                soft.append(("M5", f"number {shown} in {label} appears in no quote"))
            elif n["unit"] and (n["num"], ctx.unit_key(n["unit"])) not in have_units:
                forms = {u for u in ctx.units if ctx.unit_key(u) == ctx.unit_key(n["unit"])} | {n["unit"]}
                in_row = any(n["num"] in row_nums and any(
                    re.search(r"(?<![A-Za-z])" + re.escape(u) + r"(?![A-Za-z])", row) for u in forms)
                    for row, row_nums in rows)
                if not in_row:
                    soft.append(("M5", f"unit mismatch: no quote has {n['num']} followed by {n['unit']} ({label})"))
    derivation = fact.get("derivation")
    if soft and not (isinstance(derivation, str) and derivation.strip()):
        out += soft
    seen, unique = set(), []
    for item in out:
        if item not in seen:
            seen.add(item)
            unique.append(item)
    return unique


def _check_rest(fact, ctx):
    """M6, M7, M9, M10, M11 and M13."""
    out = []
    kind = fact.get("kind")
    qual = fact.get("qualifiers") if isinstance(fact.get("qualifiers"), dict) else {}
    if kind in QUALIFIED_KINDS:
        if not str(qual.get("scope") or "").strip():
            out.append(("M6", f"a {kind} needs qualifiers.scope (for example 'per Region, per account')"))
        if not qual.get("default_or_max"):
            out.append(("M6", f"a {kind} needs qualifiers.default_or_max"))
        if not isinstance(qual.get("adjustable"), bool):
            out.append(("M6", f"a {kind} needs qualifiers.adjustable (true or false)"))
    claim = fact.get("claim") or ""
    evidence = [e for e in fact.get("evidence") or [] if isinstance(e, dict)]
    hay = [common.normalize_text(claim)] + [common.normalize_text(e.get("quote") or "") for e in evidence]
    shown = displays(fact)
    if len(set(shown)) != len(shown):
        out.append(("M7", "two values have the same display"))
    for display in shown:
        if not display or not any(_holds(h, display) for h in hay):
            out.append(("M7", f"display {display!r} is in neither the claim nor a quote"))
    changed, volatility = fact.get("changed"), fact.get("volatility")
    if isinstance(changed, dict):
        index = changed.get("was_evidence")
        if not isinstance(index, int) or not 0 <= index < len(evidence):
            out.append(("M9", "changed.was_evidence is no index into evidence"))
        if volatility == "stable":
            out.append(("M9", "a fact with `changed` cannot have volatility stable"))
    elif volatility == "changed-since-2022":
        out.append(("M9", "volatility changed-since-2022 needs `changed`"))
    if (fact.get("source_tier") == 4) != (kind == "case-study"):
        out.append(("M10", "source_tier is 4 if and only if kind is case-study"))
    if evidence and kind != "change":
        path = urllib.parse.urlsplit(evidence[0].get("url") or "").path
        if path.startswith("/about-aws/whats-new/"):
            out.append(("M10", "evidence 0 (current truth) is a What's New post; only kind `change` allows that"))
    if fact.get("hard") is not True:
        why = None
        if kind in HARD_KINDS:
            why = f"kind {kind}"
        else:
            plain = _plain(claim)
            nums, _dates = _numbers_of(claim, ctx)
            word = _absolute_re(ctx.absolute).search(plain)
            if any((n["unit"] or n["noun"] or n["money"]) and not n["word"] for n in nums):
                why = "the claim holds a number with a unit"
            elif word:
                why = f"the claim holds the absolute word {word.group(0)!r}"
        if why:
            out.append(("M11", f"hard must be true: {why}"))
    if fact.get("hard") is True and not str(fact.get("question") or "").strip():
        out.append(("M13", "a hard fact needs a non-empty `question`"))
    return out


def mech_check(fact, ctx=None, new=False) -> list:
    """The blocking mechanical checks M1 to M11 and M13. Returns findings; empty means pass."""
    ctx = ctx or _Ctx()
    found = _check_m1(fact, ctx, new)
    if isinstance(fact, dict) and isinstance(fact.get("evidence"), list) and isinstance(fact.get("values"), list) \
            and isinstance(fact.get("claim"), str):
        if not ctx.quick:
            found += _check_evidence(fact, ctx)
            found += _check_m5(fact, ctx)
        found += _check_rest(fact, ctx)
    fid = fact.get("id") if isinstance(fact, dict) else None
    file = _rel(fact_path(fact["service"])) if isinstance(fact.get("service"), str) and re.fullmatch(
        r"[a-z0-9]+(-[a-z0-9]+)*", fact["service"]) else None
    return [_finding(code, msg, item=fid if isinstance(fid, str) else None, file=file) for code, msg in found]


def _claim_tokens(claim: str) -> set:
    return set(re.findall(r"[a-z]+", " ".join(t for t in (claim or "").lower().split() if not any(c.isdigit() for c in t))))


def _raw_numbers(claim: str) -> set:
    return {n.replace(",", "").rstrip(".") for n in re.findall(r"\d[\d,]*(?:\.\d+)?", claim or "")}


def conflict_scan(fact, ctx) -> list:
    """M12: ids of other facts of the service with a similar claim and other numbers."""
    mine, nums = _claim_tokens(fact.get("claim")), _raw_numbers(fact.get("claim"))
    hits = []
    for other in ctx.by_service.get(fact.get("service"), []):
        if other.get("id") == fact.get("id") or other.get("status") == "rejected":
            continue
        theirs = _claim_tokens(other.get("claim"))
        union = mine | theirs
        if union and len(mine & theirs) / len(union) >= 0.6 and _raw_numbers(other.get("claim")) != nums:
            hits.append(other["id"])
    return hits


