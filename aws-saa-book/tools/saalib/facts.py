def _gate(name, ch_id, errors, warnings, counts, files) -> dict:
    inputs = []
    for path in sorted({Path(p) for p in files}):
        if path.exists():
            inputs.append({"path": _rel(path), "sha256": common.sha256_file(path)})
    code = common.EXIT_FAIL if errors else (common.EXIT_WARN if warnings else common.EXIT_OK)
    return {"gate": name, "chapter": ch_id, "ok": not errors, "exit": code, "errors": errors, "warnings": warnings,
            "counts": counts, "inputs": inputs}


def gate_mech(ch_id, quick=False, **options) -> dict:
    """facts-mech: the blocking mechanical checks pass on every live fact of the chapter; at least one fact (F01)."""
    ch = common.chapter(ch_id)
    ctx = _Ctx(quick=quick)
    errors, files, checked, failed = [], set(), 0, 0
    for service, rows in ctx.by_service.items():
        mine = [r for r in rows if r.get("home_chapter") == ch["id"]]
        if mine or service in (ch.get("services") or []):
            files.add(fact_path(service))
        for fact in mine:
            if fact.get("status") in ("rejected", "superseded"):
                continue
            checked += 1
            found = mech_check(fact, ctx)
            failed += bool(found)
            errors += found
    if not checked and ch.get("services"):
        errors.append(_finding("F01", f"chapter {ch['id']} has services and no fact"))
    return _gate("facts-mech", ch["id"], errors, [], {"facts": checked, "failed": failed}, files)


def gate_final(ch_id, quick=False, **options) -> dict:
    """facts-final: every fact of the chapter and every fact it links or lists is verified (F02), none is in an
    open conflict (F03), every verified status is backed by the vote log (F04), and the mechanical checks
    still pass (M codes; skipped when quick)."""
    ch = common.chapter(ch_id)
    ctx = _Ctx(quick=quick)
    canon, where = {}, {}
    for service, rows in ctx.by_service.items():
        for row in rows:
            canon[row["id"]] = row
            where[row["id"]] = service
    conflicted = _open_conflict_ids()
    refs, files = _chapter_refs(ch["id"])
    files = set(files)
    counts = collections.Counter({k: 0 for k in ("verified", "rejected", "superseded", "candidate", "mech-pass", "disputed")})
    errors, todo = [], []
    for fid, fact in sorted(canon.items()):
        if fact.get("home_chapter") == ch["id"]:
            counts[fact.get("status")] += 1
            files.add(fact_path(where[fid]))
            if fact.get("status") not in ("rejected", "superseded"):
                todo.append(fact)
    home = {f["id"] for f in todo}
    for fid in sorted(refs - home):
        fact = canon.get(fid)
        if fact is None:
            errors.append(_finding("F02", f"fact {fid} is linked or listed by chapter {ch['id']} and is not in the canon", item=fid))
        else:
            files.add(fact_path(where[fid]))
            todo.append(fact)
    votes = {}
    for fact in todo:
        fid = fact["id"]
        if fact.get("status") != "verified":
            errors.append(_finding("F02", f"status is {fact.get('status')}, not verified", item=fid))
        if fid in conflicted:
            errors.append(_finding("F03", "the fact is in an open conflict", item=fid))
        if fact.get("status") == "verified":
            service = where[fid]
            if service not in votes:
                votes[service] = _votes(service)
                files.add(_votes_path(service))
            errors += _backing(fact, votes[service])
            if not quick:
                errors += mech_check(fact, ctx)
    counts = dict(counts)
    counts["open_conflicts"] = sum(1 for f in todo if f["id"] in conflicted)
    return _gate("facts-final", ch["id"], errors, [], counts, files)


