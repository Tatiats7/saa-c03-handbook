def _add(facts: list, label: str) -> dict:
    added, rejected, conflicts = [], [], []
    for raw in facts:
        fact = copy.deepcopy(raw)
        ctx = _Ctx()
        fact.update(rev=1, retrieved=common.today(), author=label, votes=[], status="mech-pass")
        fact.setdefault("changed", None)
        fact.setdefault("tier0", False)
        if isinstance(fact.get("evidence"), list):
            _fill_evidence(fact, ctx)
        service = fact.get("service")
        findings = mech_check(fact, ctx, new=True)
        if not findings:
            path = fact_path(service)
            with common.file_lock(path):
                rows = _rows(service)
                if any(r["id"] == fact["id"] for r in rows):
                    findings = [_finding("M1", f"id {fact['id']} is already in the canon", item=fact["id"])]
                else:
                    fact["mech"] = _mech_record([])
                    rows.append(fact)
                    _save(service, rows)
        if findings:
            common.append_jsonl(_fb() / "rejected.jsonl", {"ts": common.now_iso(), "by": label, "input": raw, "errors": findings})
            rejected.append({"id": raw.get("id"), "errors": findings})
            continue
        added.append(fact["id"])
        conflicts += _queue_conflicts(fact["id"], conflict_scan(fact, ctx))
    return {"added": added, "rejected": rejected, "conflicts": conflicts}


def _report_add(args, result) -> int:
    lines = [_text_finding(f) for r in result["rejected"] for f in r["errors"]]
    lines += [f"added {i} (mech-pass)" for i in result["added"]] + [f"conflict queued: {c}" for c in result["conflicts"]]
    _out(args, result, f"facts add: {len(result['added'])} added, {len(result['rejected'])} rejected, "
                       f"{len(result['conflicts'])} conflicts queued", lines)
    return common.EXIT_FAIL if result["rejected"] else common.EXIT_OK


