class Renderer:
    def __init__(self, ctx: Ctx, slug: str = "", ch_id: str = "", ch_dir: str = "", file: str = "", key: str = "",
                 has_quiz: bool = False, figure_counter: list = None):
        self.c = ctx
        self.slug, self.ch_id, self.ch_dir, self.file, self.key = slug, ch_id, ch_dir, file, key
        self.has_quiz = has_quiz
        self.fig_counter = figure_counter if figure_counter is not None else [0]
        self.warnings = []
        self.sections = []
        self.sec = self.sub = None
        self.linked = set()
        self.lists = {"facts": [], "terms": [], "figures": [], "traps": []}
        self.figmeta, self.trapmap, self.tasks = {}, {}, []
        self.pid_n = {}
        self.title = None
        self.offset = 0
        self.generated = False
        self.started = True
        self.last_h3 = None
        self.table_kind = None
        self.force_table_kind = None

    # ---- bookkeeping

    def warn(self, code, msg, node=None, level="warning"):
        line = (node.map[0] + 1 + self.offset) if node is not None and getattr(node, "map", None) else 0
        self.warnings.append({"code": code, "level": level, "line": line, "msg": msg})

    def target(self):
        return self.sub or self.sec

    def add(self, name, value):
        if value not in self.lists[name]:
            self.lists[name].append(value)
        entry = self.target()
        if entry is not None and value not in entry[name]:
            entry[name].append(value)

    def t(self, text):
        text = re.sub(r"\s+", " ", text or "").strip()
        if not text:
            return
        if self.sub is not None:
            self.sub["_own"].append(text)
            if self.sec is not None:
                self.sec["_full"].append(text)
        elif self.sec is not None:
            self.sec["_own"].append(text)
            self.sec["_full"].append(text)

    # ---- inline

    def autolink(self, text: str) -> str:
        if self.c.term_re is None:
            return esc(text)
        out, pos = [], 0
        for m in self.c.term_re.finditer(text):
            tid = self.c.term_of(m.group(0))
            if not tid or tid in self.linked:
                continue
            self.linked.add(tid)
            self.add("terms", tid)
            out.append(esc(text[pos:m.start()]))
            out.append(f'<a class="term" href="#glossary.{tid}" data-term="{tid}">{esc(m.group(0))}</a>')
            pos = m.end()
        out.append(esc(text[pos:]))
        return "".join(out)

    def inl(self, children, o: Opt, node=None):
        """Render inline nodes. Returns (html, plain text)."""
        out, text = [], []
        for child in children or []:
            kind = child.type
            if kind == "text":
                out.append(self.autolink(child.content) if o.auto else esc(child.content))
                text.append(child.content)
            elif kind == "softbreak":
                out.append("\n")
                text.append(" ")
            elif kind == "hardbreak":
                out.append("<br>")
                text.append(" ")
            elif kind == "code_inline":
                out.append(f"<code>{esc(child.content)}</code>")
                text.append(child.content)
            elif kind in ("strong", "em", "s"):
                h, t = self.inl(child.children, o, node)
                out.append(f"<{kind}>{h}</{kind}>")
                text.append(t)
            elif kind == "link":
                h, t = self.inl(child.children, o.no_auto(), node)
                out.append(self.link(child.attrs.get("href", ""), h, t, o, node))
                text.append(t)
            elif kind == "image":
                alt = child.content or ""
                self.warn("WB09", f"an image outside a figure paragraph is shown as its alt text: {alt[:60]}", node)
                out.append(esc(alt))
                text.append(alt)
            elif kind == "html_inline":
                raw = child.content.strip()
                if raw.startswith("<!--"):
                    continue
                m = INLINE_TAGS.match(raw)
                if m:
                    tag = m.group(1).lower()
                    if tag == "br":
                        out.append("<br>")
                        text.append(" ")
                    else:
                        out.append(("</" if raw.startswith("</") else "<") + tag + ">")
                else:
                    self.warn("WB09", f"raw HTML dropped: {raw[:60]}", node)
            else:
                self.warn("WB09", f"unknown inline construct {kind}", node)
                if child.children:
                    h, t = self.inl(child.children, o, node)
                    out.append(h)
                    text.append(t)
        return "".join(out), "".join(text)

    def link(self, href, inner, text, o: Opt, node=None) -> str:
        m = RE_FACT.match(href)
        if m:
            fid = m.group(2)
            if not fid:
                self.warn("WB03", f"link to a fact sheet without a fact id: {href}", node)
                return inner
            if fid not in self.c.facts:
                if fid in self.c.unverified:
                    self.warn("WB03", f"fact {fid} is not verified; the text stays without a link", node, "warning")
                else:
                    self.warn("WB03", f"fact {fid} does not exist", node, "error")
                return inner
            self.add("facts", fid)
            return f'<a class="ev" href="#fact.{fid}" data-fact="{fid}">{inner}</a>'
        if o.links == "fact":
            return inner
        m = RE_GLOSSARY.match(href)
        if m:
            tid = m.group(1)
            if not tid:
                return f'<a class="xr" href="#glossary">{inner}</a>'
            if tid not in self.c.term_ids:
                self.warn("WB03", f"glossary term {tid} does not exist", node, "error")
                return inner
            self.linked.add(tid)
            self.add("terms", tid)
            return f'<a class="term" href="#glossary.{tid}" data-term="{tid}">{inner}</a>'
        if re.match(r"^https?://", href):
            host = re.sub(r"^https?://([^/:?#]+).*$", r"\1", href).lower()
            if href.startswith("https://") and host in self.c.hosts:
                return f'<a class="ext" href="{att(href)}" target="_blank" rel="noopener">{inner}</a>'
            self.warn("WB09", f"external link to a host that is not allowed: {href[:80]}", node)
            return inner
        if href.startswith("#"):
            return self.section_link(self.slug, self.file, href[1:], inner, o, node)
        m = RE_SAME.match(href)
        if m:
            return self.section_link(self.slug, m.group(1), m.group(2), inner, o, node)
        m = RE_OTHER.match(href)
        if m:
            slug = self.c.chapters.get(m.group(1))
            if slug is None:
                self.warn("WB03", f"link to an unknown chapter folder: {href}", node, "error")
                return inner
            return self.section_link(slug, m.group(2), m.group(3), inner, o, node)
        self.warn("WB03", f"link target not understood: {href[:80]}", node, "error")
        return inner

    def section_link(self, slug, file, anc, inner, o: Opt, node=None) -> str:
        secs = self.c.sections.get(slug)
        if secs is None:
            self.warn("WB03", f"link to chapter {slug}, which is not built in this run", node, "warning")
            return inner
        if file in GENERATED_PARTS:
            route = f"ch.{slug}.{GENERATED_PARTS[file]}"
            if GENERATED_PARTS[file] == "do" and o.task:
                route += "." + o.task
            if inner.strip() == file:  # a link whose text is the file name reads as words in the app
                inner = {"do": "the Do part", "say": "the Say it part", "quiz": "the quiz", "sources": "the sources"}[GENERATED_PARTS[file]]
            return f'<a class="xr" href="#{route}">{inner}</a>'
        part = self.c.part_of_file.get(file)
        if part is None:
            self.warn("WB03", f"link to a file that is not a part: {file}", node, "error")
            return inner
        if not anc:
            return f'<a class="xr" href="#ch.{slug}.{part}">{inner}</a>'
        sid = (secs.get(file) or {}).get(anc)
        if sid is None:
            self.warn("WB03", f"section {file}#{anc} does not exist in chapter {slug}", node, "error")
            return inner
        return f'<a class="xr" href="#ch.{slug}.{part}.{sid}">{inner}</a>'

    # ---- sections

    def close_sub(self, out):
        if self.sub is not None:
            out.append("</div></section>")
            self.sub = None

    def close_sec(self, out):
        self.close_sub(out)
        if self.sec is not None:
            entry = self.sec
            twins = entry.get("_twins")
            if twins:
                out[entry["_idx"]] = out[entry["_idx"]].replace(' data-role="', f' data-twins="{att(twins)}" data-role="', 1)
                if self.has_quiz:
                    out.append(f'<p class="twins"><a class="xr" href="#quiz.{self.slug}">Practise this pair</a></p>')
            out.append("</div></section>")
            self.sec = None

    def entry(self, sid, title, kind, role, route, minutes, parent, service=None):
        e = {"sid": sid, "title": title, "kind": kind, "role": role, "route": route, "min": minutes, "parent": parent,
             "service": service, "facts": [], "terms": [], "figures": [], "traps": [], "_own": [], "_full": []}
        self.sections.append(e)
        return e

    def heading(self, node, nxt, out) -> int:
        """Render a heading. Returns the number of following nodes it used (the flag comment)."""
        level = int(node.tag[1])
        _, full = self.inl(node.children[0].children if node.children else [], Opt(False), node)
        full = full.strip()
        if level == 1:
            self.close_sec(out)
            title = full
            if self.generated and ": " in title:
                title = title.rsplit(": ", 1)[1]
                title = title[:1].upper() + title[1:]
            if self.title is None:
                self.title = title
            return 0
        m = RE_TIMEBOX.search(full)
        title = full[:m.start()] if m else full
        box = int(m.group(1)) if m else None
        sid = anchor(title)
        flag = nxt.content.strip() if nxt is not None and nxt.type == "html_block" else ""
        used = 0
        if level == 2:
            self.close_sec(out)
            self.linked = set()
            self.last_h3 = None
            fm = RE_FLAG.match(flag)
            if fm:
                used = 1
                role, route, minutes, service = fm.group(1), fm.group(2), int(fm.group(3)), fm.group(4)
                kind = 2
            else:
                role, route, minutes, service, kind = "sheet", "full", 0, None, 0
                if not self.generated:
                    self.warn("WB09", f"H2 without a section flag: {title}", node)
            self.sec = self.entry(sid, title, kind, role, route, minutes, None, service)
            self.sec["_idx"] = len(out)
            tbox = f'<span class="tbox">{minutes} min</span>' if kind == 2 else ""
            svc = f' data-service="{att(service)}"' if service else ""
            out.append(f'<section class="sec" id="sec-{sid}" data-sid="{sid}" data-role="{role}" data-route="{route}" '
                       f'data-min="{minutes}"{svc}><header class="sec-h"><h2>{esc(title)}</h2>{tbox}'
                       f'<button type="button" class="sec-ask" data-act="ask" hidden>Ask</button></header><div class="sec-b">')
            self.started = False
            self.t(title)
            return used
        if level == 3:
            self.close_sub(out)
            parent = self.sec
            tracked = parent is not None and parent["kind"] == 2 and (parent["role"] == "how" or box is not None)
            if tracked:
                route = parent["route"]
                if RE_FLAG_H3.match(flag):
                    used, route = 1, "pass"
                self.sub = self.entry(sid, title, 3, parent["role"], route, box or 0, parent["sid"])
                tbox = f'<span class="tbox">{box} min</span>' if box is not None else ""
                out.append(f'<section class="sub" id="sec-{sid}" data-sid="{sid}" data-route="{route}" data-min="{box or 0}">'
                           f'<header class="sub-h"><h3>{esc(title)}</h3>{tbox}</header><div class="sub-b">')
                self.started = False
            else:
                if RE_FLAG_H3.match(flag):
                    used = 1
                self.entry(sid, title, 0, parent["role"] if parent else "sheet", parent["route"] if parent else "full", 0,
                           parent["sid"] if parent else None)
                out.append(f'<h3 class="h3" id="sec-{sid}" data-sid="{sid}">{esc(title)}</h3>')
                self.started = True
            self.last_h3 = title
            self.t(title)
            return used
        self.warn("WB09", f"heading level {level} is not part of the contract: {title}", node)
        out.append(f"<p><strong>{esc(full)}</strong></p>")
        self.started = True
        return 0

    # ---- blocks

    def label_of(self, node):
        """(label text, rest of the inline children) when a paragraph starts with bold text."""
        if node.type != "paragraph" or not node.children:
            return None, None
        kids = clean(node.children[0].children)
        if not kids or kids[0].type != "strong":
            return None, None
        label = "".join(k.content for k in kids[0].children or [] if k.type == "text")
        return label, kids[1:]

    def prompt_key(self, label):
        for pattern, key in self.c.prompts:
            m = pattern.match(label or "")
            if m:
                return key, (m.group(1) if m.groups() else None)
        return None, None

    @staticmethod
    def lstrip_kids(kids):
        """A copy of the inline children whose first text node has no leading space."""
        if kids and kids[0].type == "text":
            first = kids[0]
            shadow = type("T", (), {})()
            shadow.type, shadow.content, shadow.children, shadow.attrs = "text", first.content.lstrip(), [], {}
            return [shadow] + list(kids[1:])
        return list(kids)

    def is_details(self, node):
        return node.type == "html_block" and node.content.lstrip().lower().startswith("<details")

    def details_end(self, nodes, i):
        depth = 0
        for j in range(i, len(nodes)):
            if nodes[j].type != "html_block":
                continue
            low = nodes[j].content.lower()
            depth += len(re.findall(r"<details\b", low)) - len(re.findall(r"</details>", low))
            if depth <= 0:
                return j
        return len(nodes) - 1

    def summary_of(self, node):
        m = re.search(r"<summary>(.*?)</summary>", node.content, re.S | re.I)
        return html.unescape(re.sub(r"<[^>]+>", "", m.group(1))).strip() if m else ""

    def reveal(self, nodes, i, o):
        """The reveal that starts at nodes[i]. Returns (html, index of its last node)."""
        end = self.details_end(nodes, i)
        summary = self.summary_of(nodes[i])
        inner_nodes = nodes[i + 1:end]
        if summary == "Answer":
            cls, head = "rv rv-answer", "Answer"
        elif summary == "Show the picture":
            cls, head = "rv rv-picture", "Show the picture"
        elif summary.startswith("Go deeper:"):
            cls = "rv rv-deeper"
            head = f'<span class="rv-l">Go deeper</span> {esc(summary[len("Go deeper:"):].strip())}'
            self.t(summary)
        else:
            cls, head = "rv", esc(summary)
            self.warn("WB09", f"reveal with an unknown summary: {summary[:60]}", nodes[i])
        if cls != "rv rv-deeper" and cls != "rv":
            head = esc(head)
        body = self.seq(inner_nodes, False, o)
        return f'<details class="{cls}"><summary>{head}</summary><div class="rv-b">{body}</div></details>', end

    def prompt(self, nodes, i, key, number, rest, o):
        node = nodes[i]
        label, _ = self.label_of(node)
        gist = any(name == "gist-trap" for name, _ in comments_of(node.children[0]))
        if number is None:
            self.pid_n[key] = self.pid_n.get(key, 0) + 1
            pid = f"{key}-{self.pid_n[key]}"
        else:
            pid = f"{key}-{number}"
        shown = label[:-1] if label.endswith(".") else label
        if gist:
            shown += " · careful"
        h, t = self.inl(self.lstrip_kids(rest), o, node)
        self.t(f"{label} {t}")
        out = [f'<div class="pr pr-{key}" data-pid="{pid}"' + (' data-gist="1"' if gist else "") + ">"
               f'<p class="pr-q"><span class="pr-l">{esc(shown)}</span> {h}</p>']
        end = i
        for j in range(i + 1, len(nodes)):
            cand = nodes[j]
            if cand.type == "heading":
                break
            if cand.type == "paragraph" and self.prompt_key(self.label_of(cand)[0])[0]:
                break
            if self.is_details(cand):
                if self.summary_of(cand) in ("Answer", "Show the picture"):
                    out.append(self.seq(nodes[i + 1:j], False, o))
                    rv, end = self.reveal(nodes, j, o)
                    out.append(rv)
                break
        out.append("</div>")
        return "".join(out), end

    def callout(self, node, label, o):
        key = CALLOUT_KEYS[label]
        hue = self.c.hues.get(label, "neutral")
        first = node.children[0]
        notes = comments_of(first.children[0]) if first.children else []
        attrs = ""
        local = o
        for name, value in notes:
            if name == "trap" and value:
                attrs += f' data-trap="{att(value)}"'
                self.add("traps", value)
                self.trapmap.setdefault(value, (self.target() or {}).get("sid", ""))
            elif name == "task" and value:
                attrs += f' data-task="{att(value)}"'
                local = Opt(o.auto, o.links, value)
                if value not in self.tasks:
                    self.tasks.append(value)
        kids = clean(first.children[0].children)[1:]
        if key == "changed":
            got = self.changed(node, first, hue)
            if got:
                return got
        h, t = self.inl(self.lstrip_kids(kids), local, node)
        self.t(f"{label}: {t}")
        body = f"<p>{h}</p>" + self.seq(node.children[1:], False, local)
        return (f'<aside class="co co-{key} hue-{hue}" data-label="{att(label)}"{attrs}><p class="co-l">{esc(label)}</p>'
                f'<div class="co-b">{body}</div></aside>')

    def changed(self, node, first, hue):
        kids = clean(first.children[0].children)
        segments, cur, skip = [], [], False
        for k in kids:
            if skip and k.type == "softbreak":
                skip = False
                continue
            skip = False
            if (k.type == "html_inline" and re.match(r"^<br\s*/?>$", k.content.strip(), re.I)) or k.type == "hardbreak":
                segments.append(cur)
                cur, skip = [], True
                continue
            cur.append(k)
        segments.append(cur)
        labels = []
        for seg in segments:
            if not seg or seg[0].type != "strong":
                return None
            labels.append("".join(x.content for x in seg[0].children or [] if x.type == "text"))
        if labels != CHANGED_LABELS or len(node.children) != 1:
            return None
        o = Opt(True)
        rest = self.lstrip_kids(segments[0][1:])
        date = ""
        if rest and rest[0].type == "text":
            m = RE_DATE.match(rest[0].content)
            if m:
                date = m.group(1)
                rest[0].content = rest[0].content[m.end():]
        what, what_t = self.inl(rest, o, node)
        rows, texts = [], [f"Changed recently ({date}): {what_t}"]
        status = "examinable"
        for label, seg in zip(labels[1:], segments[1:]):
            h, t = self.inl(self.lstrip_kids(seg[1:]), o, node)
            name = label[:-1]
            texts.append(f"{name}: {t}")
            if name == "Status":
                word = t.strip().rstrip(".")
                status = "not-yet" if word.lower().startswith("not") else "examinable"
                h = f'<span class="pill">{esc(word)}</span>'
            elif h.endswith("</a>."):  # a value that is one fact link: no full stop after the chip
                h = h[:-1]
            rows.append(f"<dt>{esc(name)}</dt><dd>{h}</dd>")
        self.t(" ".join(texts))
        return (f'<aside class="co co-changed hue-{hue}" data-date="{att(date)}" data-status="{status}">'
                f'<p class="co-l">Changed recently <time>{esc(date)}</time></p><p class="chg-what">{what}</p>'
                f'<dl class="chg">{"".join(rows)}</dl></aside>')

    def aws_quote(self, node):
        """An AWS quote block, or None."""
        if len(node.children) != 1 or node.children[0].type != "paragraph":
            return None
        kids = clean(node.children[0].children[0].children)
        cut = max((n for n, k in enumerate(kids) if k.type == "softbreak"), default=-1)
        if cut < 0:
            return None
        tail = kids[cut + 1:]
        if not tail or tail[0].type != "text" or not tail[0].content.startswith("— "):
            return None
        link = next((k for k in tail if k.type == "link"), None)
        head = kids[:cut]
        if link is None or not head or head[0].type != "text" or not head[0].content.startswith('"'):
            return None
        quote, quote_t = self.inl(head, Opt(False, "fact"), node)
        title, _ = self.inl(link.children, Opt(False, "fact"), node)
        href = link.attrs.get("href", "")
        host = re.sub(r"^https?://([^/:?#]+).*$", r"\1", href).lower()
        self.t(quote_t)
        if href.startswith("https://") and host in self.c.hosts:
            cite = f'<a class="ext" href="{att(href)}" target="_blank" rel="noopener">{title}</a>'
        else:
            self.warn("WB09", f"quote source on a host that is not allowed: {href[:80]}", node)
            cite = title
        return f'<figure class="awsq"><blockquote>{quote}</blockquote><figcaption>{cite}</figcaption></figure>'

    def blockquote(self, node, o):
        first = node.children[0] if node.children else None
        label, _ = self.label_of(first) if first is not None else (None, None)
        if label and label.endswith(":") and label[:-1] in CALLOUT_KEYS:
            return self.callout(node, label[:-1], o)
        quote = self.aws_quote(node)
        if quote:
            return quote
        self.warn("WB09", "blockquote that is neither a callout nor an AWS quote block", node)
        return f"<blockquote>{self.seq(node.children, False, o)}</blockquote>"

    def trap_item(self, item):
        """A traps list item, or None when the item has another form."""
        if len(item.children) != 1 or item.children[0].type != "paragraph":
            return None
        para = item.children[0]
        kids = clean(para.children[0].children)
        if not kids or kids[0].type != "strong":
            return None
        if "".join(x.content for x in kids[0].children or [] if x.type == "text") != "Wrong belief:":
            return None
        cut = next((n for n, k in enumerate(kids) if n > 0 and k.type == "strong"
                    and "".join(x.content for x in k.children or [] if x.type == "text") == "Truth:"), None)
        if cut is None:
            return None
        trap, ref = None, False
        for name, value in comments_of(para.children[0]):
            if name in ("trap", "trap-ref") and value:
                trap, ref = value, name == "trap-ref"
        wrong, wrong_t = self.inl(self.lstrip_kids(kids[1:cut]), Opt(False), para)
        truth, truth_t = self.inl(self.lstrip_kids(kids[cut + 1:]), Opt(True), para)
        self.t(f"Wrong belief: {wrong_t} Truth: {truth_t}")
        attr = ""
        if trap:
            attr = f' data-trap="{att(trap)}"'
            self.add("traps", trap)
            if not ref:
                self.trapmap.setdefault(trap, (self.target() or {}).get("sid", ""))
        return (f'<li class="trap"{attr}><p class="trap-w"><span class="bf-l">Wrong belief</span> {wrong.rstrip()}</p>'
                f'<p class="trap-t"><span class="bf-l">Truth</span> {truth.rstrip()}</p></li>')

    def list_block(self, node, o, cls=None):
        tag = "ol" if node.type == "ordered_list" else "ul"
        items = node.children or []
        if tag == "ul" and items:
            traps = [self.trap_item(it) for it in items[:1]]
            if traps[0] is not None:
                rows = [traps[0]]
                for it in items[1:]:
                    got = self.trap_item(it)
                    rows.append(got if got is not None else f"<li>{self.item(it, o)}</li>")
                return f'<ul class="traps">{"".join(rows)}</ul>'
        start = node.attrs.get("start") if tag == "ol" else None
        attrs = (f' class="{cls}"' if cls else "") + (f' start="{int(start)}"' if start not in (None, 1, "1") else "")
        return f"<{tag}{attrs}>" + "".join(f"<li>{self.item(it, o)}</li>" for it in items) + f"</{tag}>"

    def item(self, item, o):
        kids = item.children or []
        if len(kids) == 1 and kids[0].type == "paragraph":
            h, t = self.inl(kids[0].children[0].children if kids[0].children else [], o, kids[0])
            self.t(t)
            return h
        return self.seq(kids, False, o)

    def table(self, node, o):
        kind = self.force_table_kind or self.table_kind or "plain"
        self.table_kind = None
        if kind not in self.c.table_kinds:
            self.warn("WB09", f"unknown table kind {kind}; rendered as a plain table", node)
            kind = "plain"
        head_rows = [tr for part in node.children if part.type == "thead" for tr in part.children]
        body_rows = [tr for part in node.children if part.type == "tbody" for tr in part.children]
        headers, head_html = [], []
        for tr in head_rows:
            cells = []
            for th in tr.children:
                h, t = self.inl(th.children[0].children if th.children else [], Opt(False), node)
                headers.append(t.strip())
                cells.append(f'<th scope="col">{h}</th>')
            head_html.append("<tr>" + "".join(cells) + "</tr>")
            self.t(" | ".join(headers))
        body_html = []
        for tr in body_rows:
            cells, texts = [], []
            for n, td in enumerate(tr.children):
                kids = td.children[0].children if td.children else []
                th_name = att(headers[n]) if n < len(headers) else ""
                if kind == "words" and n == 0:
                    h, t = self.words_cell(kids, node)
                    cells.append(f'<th scope="row" data-th="{th_name}">{h}</th>')
                else:
                    auto = not (kind == "signals" and n == 0)
                    h, t = self.inl(kids, Opt(auto and o.auto, o.links), node)
                    cells.append(f'<td data-th="{th_name}">{h}</td>')
                texts.append(t.strip())
            body_html.append("<tr>" + "".join(cells) + "</tr>")
            self.t(" | ".join(texts))
        stack = " tb-stack" if kind in STACK_KINDS else ""
        label = att(headers[0]) if headers else ""
        out = (f'<div class="tw" role="region" tabindex="0" aria-label="Table: {label}"><table class="tb tb-{kind}{stack}">'
               f'<thead>{"".join(head_html)}</thead><tbody>{"".join(body_html)}</tbody></table></div>')
        if kind == "log":
            out += '<div class="mount" data-mount="mistakes"></div>'
        return out

    def words_cell(self, kids, node):
        h, t = self.inl(kids, Opt(False), node)
        name = re.sub(r"\s*\([^()]*\)\s*$", "", t).strip()
        tid = self.c.term_of(name)
        if tid is None and anchor(name) in self.c.term_ids:
            tid = anchor(name)
        if tid is None or not h.startswith(esc(name)):
            return h, t
        self.linked.add(tid)
        self.add("terms", tid)
        return f'<a class="term" href="#glossary.{tid}" data-term="{tid}">{esc(name)}</a>{h[len(esc(name)):]}', t

    def figure(self, nodes, i, o):
        """A diagram embed that starts at nodes[i]. Returns (html, index of its last node) or None."""
        node = nodes[i]
        kids = clean(node.children[0].children) if node.children else []
        if len(kids) != 1 or kids[0].type != "image":
            return None
        m = RE_DIAGRAM.match(kids[0].attrs.get("src", ""))
        if not m:
            return None
        fid = m.group(1)
        alt = kids[0].content or ""
        end = i
        caption = caption_t = ""
        steps = []
        if i + 1 < len(nodes):
            label, rest = self.label_of(nodes[i + 1])
            if label == "Figure.":
                caption, caption_t = self.inl(self.lstrip_kids(rest), o, nodes[i + 1])
                end = i + 1
                if i + 2 < len(nodes) and nodes[i + 2].type == "ordered_list":
                    for it in nodes[i + 2].children or []:
                        para = it.children[0] if it.children and it.children[0].type == "paragraph" else None
                        h, t = self.inl(para.children[0].children, o, para) if para is not None and para.children else ("", "")
                        steps.append((h, t))
                    end = i + 2
        self.fig_counter[0] += 1
        number = f"{self.ch_id}.{self.fig_counter[0]}" if self.ch_id else str(self.fig_counter[0])
        info = self.c.diagrams.get(fid) or {}
        drawing = info.get("html") or f'<p class="fig-missing">{esc(alt)}</p>'
        if not info.get("html"):
            self.warn("WB04", f"diagram {fid} has no spec and no SVG file; the figure shows its description only", node)
        self.add("figures", fid)
        self.figmeta[fid] = {"n": number, "alt": alt, "claim": caption_t.strip(), "steps": [t.strip() for _, t in steps]}
        self.t(f"Figure {number}. {caption_t} " + " ".join(f"{n}. {t}" for n, (_, t) in enumerate(steps, 1)))
        steps_html = '<ol class="fig-steps">' + "".join(f"<li>{h}</li>" for h, _ in steps) + "</ol>" if steps else ""
        out = (f'<figure class="fig" data-fig="{att(fid)}" data-kind="{att(info.get("kind") or "image")}">'
               f'<div class="fig-h"><span class="fig-n">Figure {esc(number)}</span> <span class="fig-t">{esc(info.get("title") or "")}</span></div>'
               f'<div class="fig-s" role="region" tabindex="0" aria-label="Figure: {att(alt)}">{drawing}</div>'
               f'<figcaption class="fig-c">{caption}</figcaption>{steps_html}'
               '<div class="fig-a"><button type="button" data-act="zoom">Zoom</button>'
               '<button type="button" data-act="describe">Describe</button></div>'
               f'<p class="fig-alt" hidden>{esc(alt)}</p></figure>')
        return out, end

    def html_block(self, node, out):
        raw = node.content.strip()
        bodies = RE_COMMENT.findall(raw)
        if bodies and not RE_COMMENT.sub("", raw).strip():
            for body in bodies:
                name, _, value = body.strip().partition(":")
                name, value = name.strip(), value.strip()
                if name == "table":
                    self.table_kind = value
                elif name == "saa-mount":
                    mount, _, ident = value.partition(" ")
                    out.append(f'<div class="mount" data-mount="{att(mount)}" data-id="{att(ident.strip())}"></div>')
                    self.started = True
                elif name == "saa-force-table":
                    self.force_table_kind = value or None
                elif name == "twins" and self.sec is not None:
                    self.sec["_twins"] = " ".join(value.split())
            return
        if re.match(r"^</(details|summary)>$", raw, re.I):
            return
        self.warn("WB09", f"raw HTML block dropped: {raw[:60]}", node)

    def seq(self, nodes, top, o=None) -> str:
        o = o or Opt()
        out = []
        i = 0
        nodes = list(nodes)
        while i < len(nodes):
            node = nodes[i]
            kind = node.type
            i += 1
            if kind == "heading":
                if not top:
                    _, t = self.inl(node.children[0].children if node.children else [], Opt(False), node)
                    self.warn("WB09", f"heading inside another block: {t[:60]}", node)
                    out.append(f"<p><strong>{esc(t)}</strong></p>")
                    continue
                i += self.heading(node, nodes[i] if i < len(nodes) else None, out)
                continue
            if kind == "html_block":
                if self.is_details(node):
                    rv, end = self.reveal(nodes, i - 1, o)
                    out.append(rv)
                    i = end + 1
                    if top:
                        self.started = True
                else:
                    self.html_block(node, out)
                continue
            block = None
            lede = False
            if kind == "paragraph":
                fig = self.figure(nodes, i - 1, o)
                if fig:
                    block, end = fig
                    i = end + 1
                else:
                    label, rest = self.label_of(node)
                    pkey, number = self.prompt_key(label)
                    if pkey:
                        block, end = self.prompt(nodes, i - 1, pkey, number, rest, o)
                        i = end + 1
                    elif label in self.c.bold_fields or label in DECIDE_FIELDS:
                        h, t = self.inl(self.lstrip_kids(rest), o, node)
                        self.t(f"{label} {t}")
                        cls = "bf bf-decide" if label in DECIDE_FIELDS else "bf"
                        name = DECIDE_FIELDS.get(label) or slug_of(label)
                        block = f'<p class="{cls}" data-f="{name}"><span class="bf-l">{esc(label)}</span> {h}</p>'
                        if label in LIST_FIELDS and i < len(nodes) and nodes[i].type in ("bullet_list", "ordered_list"):
                            block += self.list_block(nodes[i], o, "bf-list")
                            i += 1
                    else:
                        h, t = self.inl(node.children[0].children if node.children else [], o, node)
                        self.t(t)
                        if not h.strip():
                            continue
                        lede = top and not self.started and (self.sub is not None or self.sec is not None)
                        block = f'<p class="lede">{h}</p>' if lede else f"<p>{h}</p>"
            elif kind == "blockquote":
                block = self.blockquote(node, o)
            elif kind in ("bullet_list", "ordered_list"):
                block = self.list_block(node, o)
            elif kind == "table":
                block = self.table(node, o)
            elif kind in ("fence", "code_block"):
                block = code_block(node.content, node.info if kind == "fence" else "text")
            elif kind == "hr":
                block = "<hr>"
            else:
                self.warn("WB09", f"unknown block construct {kind}", node)
                continue
            out.append(block)
            if top:
                self.started = True
        if top:
            self.close_sec(out)
        return "".join(out)

