class Ctx:
    def __init__(self, ctx: dict):
        self.facts = ctx.get("facts") or {}
        self.unverified = set(ctx.get("unverified") or [])
        self.chapters = ctx.get("chapters") or {}
        self.part_of_file = ctx.get("part_of_file") or {}
        self.sections = ctx.get("sections") or {}
        self.diagrams = ctx.get("diagrams") or {}
        self.hosts = set(ctx.get("hosts") or [])
        self.table_kinds = set(ctx.get("table_kinds") or []) | {"plain"}
        self.hues = {}
        for row in ctx.get("callouts") or []:
            if isinstance(row, dict) and row.get("label"):
                self.hues[row["label"]] = row.get("hue") or "neutral"
        self.prompts = []
        labels = ctx.get("prompts") or [p[0] for p in PROMPT_KEYS]
        for label, key in PROMPT_KEYS:
            if label in labels:
                pattern = re.escape(label).replace(re.escape("<n>"), r"(\d+)")
                self.prompts.append((re.compile("^" + pattern + "$"), key))
        self.bold_fields = set()
        fields = ctx.get("bold_fields") or []
        if isinstance(fields, dict):
            for value in fields.values():
                if isinstance(value, list):
                    self.bold_fields.update(v for v in value if isinstance(v, str))
        else:
            self.bold_fields.update(fields)
        self.term_ids = set()
        self.term_exact, self.term_lower, alts = {}, {}, []
        for term in ctx.get("terms") or []:
            self.term_ids.add(term["id"])
            for form in term.get("forms") or []:
                if not form or not form.strip():
                    continue
                if term.get("cs"):
                    self.term_exact.setdefault(form, term["id"])
                    alts.append((len(form), re.escape(form)))
                else:
                    self.term_lower.setdefault(form.lower(), term["id"])
                    alts.append((len(form), "(?i:" + re.escape(form) + ")"))
        alts.sort(key=lambda a: (-a[0], a[1]))
        self.term_re = re.compile(r"(?<![A-Za-z0-9-])(?:" + "|".join(a[1] for a in alts) + r")(?![A-Za-z0-9-])") if alts else None

    def term_of(self, text: str):
        return self.term_exact.get(text) or self.term_lower.get(text.lower())


class Opt:
    """Inline options: auto = link glossary terms; links = 'all' or 'fact'; task = task id of a Try it callout."""
    def __init__(self, auto=True, links="all", task=None):
        self.auto, self.links, self.task = auto, links, task

    def no_auto(self):
        return Opt(False, self.links, self.task)


def clean(children) -> list:
    """Inline children without the empty text nodes that markdown-it puts before emphasis."""
    return [c for c in children or [] if not (c.type == "text" and c.content == "")]


def comments_of(node) -> list:
    """Every (name, value) comment inside an inline subtree, in order."""
    out = []
    for child in node.children or []:
        if child.type == "html_inline":
            for body in RE_COMMENT.findall(child.content):
                name, _, value = body.strip().partition(":")
                out.append((name.strip(), value.strip()))
        elif child.children:
            out += comments_of(child)
    return out


