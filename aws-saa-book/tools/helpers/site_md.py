def highlight(code: str, lang: str) -> str:
    try:
        lexer = get_lexer_by_name(lang) if lang and lang != "text" else None
    except ClassNotFound:
        lexer = None
    if lexer is None:
        return esc(code)
    out = []
    for ttype, value in lex(code, lexer):
        cls = None
        if ttype in Token.Comment:
            cls = "tok-com"
        elif ttype in Token.Keyword or ttype in Token.Name.Tag or ttype in Token.Name.Builtin:
            cls = "tok-kw"
        elif ttype in Token.Literal.String:
            cls = "tok-str"
        elif ttype in Token.Literal.Number:
            cls = "tok-num"
        if cls and value.strip():
            body = value.strip()
            lead = value[:len(value) - len(value.lstrip())]
            out.append(f'{esc(lead)}<span class="{cls}">{esc(body)}</span>{esc(value[len(lead) + len(body):])}')
        else:
            out.append(esc(value))
    text = "".join(out)
    return text[:-1] if text.endswith("\n") and not code.endswith("\n") else text


def code_block(code: str, lang: str) -> str:
    code = code[:-1] if code.endswith("\n") else code
    lang = (lang or "text").strip().split()[0] if (lang or "").strip() else "text"
    return (f'<div class="code" data-lang="{att(lang)}"><button type="button" class="code-copy" data-act="copy">Copy</button>'
            f'<pre tabindex="0"><code>{highlight(code, lang)}</code></pre></div>')


