"""Generate saalib/diagram/_widths.py: advance widths of Arial regular and bold.

Run once (the output is committed, the runtime stays standard library):

    uv run --script aws-saa-book/tools/helpers/gen_font_widths.py

Widths are in 1/1000 em. Arial and Helvetica share metrics by design, so one table serves the
font stack "Helvetica Neue", Helvetica, Arial, sans-serif.
"""
from pathlib import Path

from fontTools.ttLib import TTFont

FONTS = {
    "regular": "/System/Library/Fonts/Supplemental/Arial.ttf",
    "bold": "/System/Library/Fonts/Supplemental/Arial Bold.ttf",
}
EXTRA = " ·×é–—‘’“”•…→←↔≤≥µ°±"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)

OUT = Path(__file__).resolve().parent.parent / "saalib" / "diagram" / "_widths.py"


def table(path: str) -> dict:
    font = TTFont(path)
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    out = {}
    for ch in CHARS:
        glyph = cmap.get(ord(ch))
        if glyph is None:
            continue
        out[ch] = round(hmtx[glyph][0] * 1000 / upm)
    return out


def main() -> None:
    lines = ['"""Generated by tools/helpers/gen_font_widths.py from Arial (fontTools). Do not edit.',
             "",
             "Advance widths in 1/1000 em, without kerning.",
             '"""',
             ""]
    for name, path in FONTS.items():
        widths = table(path)
        lines.append(f"{name.upper()} = {{")
        for ch in sorted(widths):
            lines.append(f"    {ch!r}: {widths[ch]},")
        lines.append("}")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(CHARS)} characters per face)")


if __name__ == "__main__":
    main()
